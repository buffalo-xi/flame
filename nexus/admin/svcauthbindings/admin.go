var repository = repo.NewRepository()

// RegisterRoutes registers the /svcauthbindings management endpoints (the caller already adds the
// /svcauthbindings prefix)
func RegisterRoutes(router *gin.RouterGroup) {
	router.GET("", listBindings)
	router.POST("/create", createBinding)
	router.PUT("/:id", updateBinding)
	router.DELETE("/:id", deleteBinding)
	// Endpoint reach (granted per agent / flow target, covering every protocol endpoint of that target)
	router.GET("/target-candidates", listTargetCandidates)
	router.GET("/:id/targets", getBindingTargets)
	router.PUT("/:id/targets", setBindingTargets)
}

// authInfoOf reads the current request's tenant auth info.
func authInfoOf(c *gin.Context) (*auth.AuthInfo, bool) {
	authInfo, exists := c.Get("authInfo")
	if !exists {
		xhttp.ErrCode(c, "common.internal", nil, "Authentication info not found", "")
		return nil, false
	}
	info, ok := authInfo.(*auth.AuthInfo)
	if !ok {
		xhttp.ErrCode(c, "common.internal", nil, "Authentication information not found", "")
		return nil, false
	}
	return info, true
}

// ensureUserExists verifies that the binding's target user exists.
// A binding only gives a service call an identity (for auditing), so the role is not checked - a
// management user can be bound just as well; a disabled account is not rejected either (the
// service side refuses it by status, and the binding works again once the account is restored).
func ensureUserExists(schema, userID string) error {
	if userID == "" {
		return fmt.Errorf("user_id is required")
	}
	var ok bool
	err := db.DB.QueryRow(`SELECT true FROM `+schema+`.users WHERE id = $1`, userID).Scan(&ok)
	if err == sql.ErrNoRows {
		return fmt.Errorf("user not found: %s", userID)
	}
	return err
}

// bindingToMap turns a binding into a response map.
func bindingToMap(b *models.SvcAuthBinding) gin.H {
	return gin.H{
		"id":                 b.ID,
		"auth_type":          b.AuthType,
		"external_issuer":    b.ExternalIssuer,
		"external_subject":   b.ExternalSubject,
		"user_id":            b.UserID,
		"is_active":          b.IsActive,
		"restrict_targets":   b.RestrictTargets,
		"exclude_supervisor": b.ExcludeSupervisor,
		"target_count":       b.TargetCount,
		"created_at":         b.CreatedAt,
		"updated_at":         b.UpdatedAt,
	}
}

// listBindings GET /svcauthbindings?auth_type=apikey
func listBindings(c *gin.Context) {
	info, ok := authInfoOf(c)
	if !ok {
		return
	}
	authType := strings.TrimSpace(c.Query("auth_type"))
	list, err := repository.List(info.Schema, authType)
	if err != nil {
		xhttp.ErrCode(c, "common.internal", nil, "failed to list bindings: "+err.Error(), "")
		return
	}
	items := make([]gin.H, 0, len(list))
	for i := range list {
		items = append(items, bindingToMap(&list[i]))
	}
	xhttp.OkJSON(c, "Success", gin.H{"items": items}, "")
}

type createRequest struct {
	AuthType        string `json:"auth_type" binding:"required"` // apikey | oauth
	ExternalIssuer  string `json:"external_issuer"`              // oauth only (iss)
	ExternalSubject string `json:"external_subject"`             // oauth: sub; apikey: generated by the backend when empty
	UserID          string `json:"user_id" binding:"required"`   // users.id
}

// createBinding POST /svcauthbindings/create
func createBinding(c *gin.Context) {
	info, ok := authInfoOf(c)
	if !ok {
		return
	}
	var req createRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		xhttp.ErrCode(c, "common.invalid_params", nil, "Invalid request body: "+err.Error(), "")
		return
	}
	if req.AuthType != "apikey" && req.AuthType != "oauth" {
		xhttp.ErrCode(c, "binding.invalid_auth_type", nil, "auth_type must be 'apikey' or 'oauth'", "")
		return
	}

	subject := strings.TrimSpace(req.ExternalSubject)
	issuer := strings.TrimSpace(req.ExternalIssuer)
	if req.AuthType == "apikey" {
		// apikey: the issuer is always empty; when no subject is given the backend generates a plain
		// secret. The key looks like sk-<random> and no longer carries a tenant prefix: the tenant comes
		// from the request path /service/{mcp|rpc}/{schema}, and that segment in the key takes part in
		// neither validation nor routing - keeping it only suggests a different tenant needs a
		// different key.
		issuer = ""
		if subject == "" {
			generated, err := auth.GenerateAPIKey("")
			if err != nil {
				xhttp.ErrCode(c, "common.internal", nil, "failed to generate secret: "+err.Error(), "")
				return
			}
			subject = generated
		}
	} else {
		// oauth: sub is required, iss may be empty (the issuer is not enforced)
		if subject == "" {
			xhttp.ErrCode(c, "binding.external_subject_required", nil, "external_subject (sub) is required for oauth", "")
			return
		}
	}

	userID := strings.TrimSpace(req.UserID)
	if err := ensureUserExists(info.Schema, userID); err != nil {
		xhttp.ErrCode(c, "common.invalid_params", nil, "invalid user_id: "+err.Error(), "")
		return
	}

	b := &models.SvcAuthBinding{
		AuthType:        req.AuthType,
		ExternalIssuer:  issuer,
		ExternalSubject: subject,
		UserID:          userID,
		IsActive:        true,
	}
	if err := repository.Create(info.Schema, b); err != nil {
		xhttp.ErrCode(c, "common.internal", nil, "failed to create binding: "+err.Error(), "")
		return
	}
	xhttp.OkJSON(c, "Success", bindingToMap(b), "")
}

type updateRequest struct {
	UserID          string `json:"user_id" binding:"required"`
	ExternalSubject string `json:"external_subject"` // optional: supplied when rotating an apikey secret
	IsActive        bool   `json:"is_active"`
}

// updateBinding PUT /svcauthbindings/:id
func updateBinding(c *gin.Context) {
	info, ok := authInfoOf(c)
	if !ok {
		return
	}
	id := c.Param("id")

	existing, err := repository.GetByID(info.Schema, id)
	if err != nil {
		xhttp.ErrCode(c, "common.internal", nil, "failed to get binding: "+err.Error(), "")
		return
	}
	if existing == nil {
		xhttp.ErrCode(c, "binding.not_found", nil, "Binding not found", "")
		return
	}

	var req updateRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		xhttp.ErrCode(c, "common.invalid_params", nil, "Invalid request body: "+err.Error(), "")
		return
	}

	// Rebinding to another user verifies the target exists (same rule as create: existence only,
	// no role restriction)
	if newUserID := strings.TrimSpace(req.UserID); newUserID != existing.UserID {
		if err := ensureUserExists(info.Schema, newUserID); err != nil {
			xhttp.ErrCode(c, "common.invalid_params", nil, "invalid user_id: "+err.Error(), "")
			return
		}
	}

	existing.UserID = strings.TrimSpace(req.UserID)
	existing.IsActive = req.IsActive
	if s := strings.TrimSpace(req.ExternalSubject); s != "" {
		existing.ExternalSubject = s
	}

	if err := repository.Update(info.Schema, existing); err != nil {
		xhttp.ErrCode(c, "common.internal", nil, "failed to update binding: "+err.Error(), "")
		return
	}
	xhttp.OkJSON(c, "Success", bindingToMap(existing), "")
}

// deleteBinding DELETE /svcauthbindings/:id
func deleteBinding(c *gin.Context) {
	info, ok := authInfoOf(c)
	if !ok {
		return
	}
	id := c.Param("id")
	if err := repository.Delete(info.Schema, id); err != nil {
		xhttp.ErrCode(c, "common.internal", nil, "failed to delete binding: "+err.Error(), "")
		return
	}
	xhttp.OkJSON(c, "Success", id, "")
}

// listTargetCandidates GET /svcauthbindings/target-candidates
//
// The grantable candidates are agents / flows with **exposed endpoints**. A target without an
// endpoint cannot be called even when it is ticked, and listing it would only make people think it
// is configured.
func listTargetCandidates(c *gin.Context) {
	info, ok := authInfoOf(c)
	if !ok {
		return
	}
	items, err := repository.ListTargetCandidates(info.Schema)
	if err != nil {
		xhttp.ErrCode(c, "common.internal", nil, "failed to list target candidates: "+err.Error(), "")
		return
	}
	xhttp.OkJSON(c, "Success", gin.H{"items": items}, "")
}

// getBindingTargets GET /svcauthbindings/:id/targets
func getBindingTargets(c *gin.Context) {
	info, ok := authInfoOf(c)
	if !ok {
		return
	}
	restrict, excludeSupervisor, targets, err := repository.GetTargets(info.Schema, c.Param("id"))
	if err != nil {
		if err == sql.ErrNoRows {
			xhttp.ErrCode(c, "binding.not_found", nil, "binding not found", "")
			return
		}
		xhttp.ErrCode(c, "common.internal", nil, "failed to load targets: "+err.Error(), "")
		return
	}
	xhttp.OkJSON(c, "Success", gin.H{
		"restrict":           restrict,
		"exclude_supervisor": excludeSupervisor,
		"targets":            targets,
	}, "")
}

type setTargetsRequest struct {
	Restrict bool `json:"restrict"`
	// ExcludeSupervisor only applies when Restrict=false: it does not limit all endpoints but
	// excludes the supervisor agent.
	ExcludeSupervisor bool `json:"exclude_supervisor"`
	Targets           []struct {
		TargetType string `json:"target_type"`
		TargetID   string `json:"target_id"`
	} `json:"targets"`
}

// setBindingTargets PUT /svcauthbindings/:id/targets
//
// A full replacement. Semantics: with restrict=false the allow-list has no effect (the data is kept
// so reopening restores it as it was); restrict=true with an empty list means this credential can
// call no endpoint at all.
func setBindingTargets(c *gin.Context) {
	info, ok := authInfoOf(c)
	if !ok {
		return
	}
	var req setTargetsRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		xhttp.ErrCode(c, "common.invalid_params", nil, "Invalid request body: "+err.Error(), "")
		return
	}

	// A target must exist and have at least one exposed endpoint - otherwise it is a dead entry that
	// can never be called
	candidates, err := repository.ListTargetCandidates(info.Schema)
	if err != nil {
		xhttp.ErrCode(c, "common.internal", nil, "failed to load target candidates: "+err.Error(), "")
		return
	}
	valid := make(map[string]bool, len(candidates))
	for _, t := range candidates {
		valid[t.TargetType+":"+t.TargetID] = true
	}

	targets := make([]repo.BindingTarget, 0, len(req.Targets))
	seen := make(map[string]bool, len(req.Targets))
	for _, t := range req.Targets {
		tt := strings.TrimSpace(t.TargetType)
		tid := strings.TrimSpace(t.TargetID)
		if tt != "agent" && tt != "flow" {
			xhttp.ErrCode(c, "binding.invalid_target_type", nil, "target_type must be 'agent' or 'flow'", "")
			return
		}
		if tid == "" {
			xhttp.ErrCode(c, "binding.target_id_required", nil, "target_id is required", "")
			return
		}
		key := tt + ":" + tid
		if !valid[key] {
			xhttp.ErrCode(c, "binding.target_not_exposed", gin.H{"target": key}, fmt.Sprintf("target %s has no exposed endpoint and cannot be granted", key), "")
			return
		}
		if seen[key] {
			continue
		}
		seen[key] = true
		targets = append(targets, repo.BindingTarget{TargetType: tt, TargetID: tid})
	}

	// The two modes are mutually exclusive: under the restricted mode "exclude the supervisor agent"
	// is meaningless (the allow-list already says it exactly), and the repo stores it as false
	if err := repository.SetTargets(info.Schema, c.Param("id"), req.Restrict, req.ExcludeSupervisor, targets); err != nil {
		if err == sql.ErrNoRows {
			xhttp.ErrCode(c, "binding.not_found", nil, "binding not found", "")
			return
		}
		xhttp.ErrCode(c, "common.internal", nil, "failed to save targets: "+err.Error(), "")
		return
	}
	excludeSupervisor := req.ExcludeSupervisor && !req.Restrict
	xhttp.OkJSON(c, "Success", gin.H{
		"restrict":           req.Restrict,
		"exclude_supervisor": excludeSupervisor,
		"count":              len(targets),
	}, "")
}
