// ===== Node queries / rewrites on the diagram =====

// parentOf returns the container a node belongs to ("" = top level).
func (d *flowDoc) parentOf(id string) string {
	if n, ok := d.node(id); ok {
		return n.ParentNode
	}
	return ""
}

// subtree returns id and all of its descendants (the whole subtree when containers are nested).
func (d *flowDoc) subtree(id string) []string {
	out := []string{id}
	for grew := true; grew; {
		grew = false
		for _, n := range d.nodes {
			if n.ParentNode == "" || containsStr(out, n.ID) {
				continue
			}
			if containsStr(out, n.ParentNode) {
				out = append(out, n.ID)
				grew = true
			}
		}
	}
	return out
}

// ancestorIs walks up from id looking for an ancestor container of type typ.
// isOrInside reports whether id is a container of the given type itself, or sits inside one. The "itself" half matters for
// tools that take a parent_node: a node created directly under a function has the function as its parent, not as an
// ancestor.
func (d *flowDoc) isOrInside(id, typ string) bool {
	if n, ok := d.node(id); ok && n.Type == typ {
		return true
	}
	return d.ancestorIs(id, typ)
}

func (d *flowDoc) ancestorIs(id, typ string) bool {
	cur := id
	for i := 0; i < 32 && cur != ""; i++ {
		n, ok := d.node(cur)
		if !ok || n.ParentNode == "" {
			return false
		}
		p, ok := d.node(n.ParentNode)
		if !ok {
			return false
		}
		if p.Type == typ {
			return true
		}
		cur = p.ID
	}
	return false
}

// loopScope reports whether a break / continue placed under parentID can reach a loop: "loop" (a loop above it; process /
// branch / fork are transparent), "function" (a function boundary comes first, and it is isolation), or "" at the top level.
//
// Kept in step with the two other places that answer the same question: control.go signalScope (the run time) and
// flowcheck's control_scope (the static check). Three copies of one rule is one too many; the errors name the same shape.
func (d *flowDoc) loopScope(parentID string) string {
	cur := parentID
	for i := 0; i < 32 && cur != ""; i++ {
		n, ok := d.node(cur)
		if !ok {
			return ""
		}
		switch n.Type {
		case "loop":
			return "loop"
		case "function":
			return "function"
		}
		cur = n.ParentNode
	}
	return ""
}

// positionFor computes a placement for a new node that does not overlap existing ones, with the same rule as create_flow's
// layout: at the top level it continues to the right of the current rightmost node (same y), wrapping to the next row past the
// width of a row; inside a container, children are stacked vertically.
func (d *flowDoc) positionFor(parentID string) map[string]int {
	if parentID != "" {
		maxBottom := childBaseY
		for _, n := range d.nodes {
			if n.ParentNode != parentID {
				continue
			}
			h := 32
			if containerTypes[n.Type] {
				h = 100
			}
			if bottom := n.Position.Y + h; bottom > maxBottom {
				maxBottom = bottom
			}
		}
		return map[string]int{"x": childBaseX, "y": maxBottom + childGap}
	}

	rightX, rowY := 0, 0
	for _, n := range d.nodes {
		if n.ParentNode != "" {
			continue
		}
		if n.Position.X >= rightX {
			rightX = n.Position.X
			rowY = n.Position.Y
		}
	}
	// The step matches the skill doc's "adjacent leaves step 200 in x", so an appended node is never spaced wider than
	// hand-written coordinates
	if x := rightX + 200; x <= layoutRowMaxWidth {
		return map[string]int{"x": x, "y": rowY}
	}
	// It does not fit on one row: wrap to the next row, below the lowest existing node
	maxBottom := 0
	for _, n := range d.nodes {
		if n.ParentNode != "" {
			continue
		}
		if bottom := n.Position.Y + 32; bottom > maxBottom {
			maxBottom = bottom
		}
	}
	return map[string]int{"x": 0, "y": maxBottom + layoutRowGap}
}

// positionBelowFlow places a top-level node under the whole graph: a function node is entered by a call, not by an edge, so
// it must not continue the main row (positionFor would append it to the right of the last step).
func (d *flowDoc) positionBelowFlow() map[string]int {
	bottom := layoutMarginY
	for _, n := range d.nodes {
		if n.ParentNode != "" {
			continue
		}
		// Containers carry their own config.size; the estimate only has to be large enough to leave a visible gap.
		h := 40
		if containerTypes[n.Type] {
			h = 240
		}
		if b := n.Position.Y + h; b > bottom {
			bottom = b
		}
	}
	return map[string]int{"x": layoutMarginX, "y": bottom + layoutOrphanGap}
}

// nodeConfigOf decodes a node's data.config into a generic object (used for reference scanning / config changes).
func nodeConfigOf(raw json.RawMessage) map[string]any {
	var n struct {
		Data struct {
			Config map[string]any `json:"config"`
		} `json:"data"`
	}
	_ = json.Unmarshal(raw, &n)
	if n.Data.Config == nil {
		return map[string]any{}
	}
	return n.Data.Config
}

// patchNodeJSON changes only the keys the caller names, keeping everything else (coordinates, sizes, extent, frontend-private
// fields) as it was.
func patchNodeJSON(raw json.RawMessage, apply func(node, data map[string]json.RawMessage) error) (json.RawMessage, error) {
	var node map[string]json.RawMessage
	if err := json.Unmarshal(raw, &node); err != nil {
		return nil, fmt.Errorf("failed to parse node JSON: %w", err)
	}
	data := map[string]json.RawMessage{}
	if d := node["data"]; len(d) > 0 {
		if err := json.Unmarshal(d, &data); err != nil {
			return nil, fmt.Errorf("failed to parse node data: %w", err)
		}
	}
	if err := apply(node, data); err != nil {
		return nil, err
	}
	db, err := json.Marshal(data)
	if err != nil {
		return nil, err
	}
	node["data"] = db
	return json.Marshal(node)
}

// referencesTo finds references to these ids from nodes outside the subtree (they must be caught before a delete: a reference
// does not disappear with its target).
func (d *flowDoc) referencesTo(targets map[string]bool) []string {
	var refs []string
	for i := range d.nodes {
		n := &d.nodes[i]
		if targets[n.ID] {
			continue
		}
		cfg := nodeConfigOf(d.nodeRaw[i])
		if inputs, ok := cfg["inputs"].(map[string]any); ok {
			for key, v := range inputs {
				in, ok := v.(map[string]any)
				if !ok {
					continue
				}
				if ref, _ := in["source_ref"].(string); ref != "" && targets[ref] {
					refs = append(refs, fmt.Sprintf("node %s (%s) config.inputs.%s.source_ref", n.ID, n.Type, key))
				}
			}
		}
		if ref, _ := cfg["target"].(string); ref != "" && targets[ref] {
			refs = append(refs, fmt.Sprintf("node %s (%s) config.target (call target)", n.ID, n.Type))
		}
	}
	return refs
}

// nodeView is the node view echoed back (coordinates included: the caller uses them to decide whether position needs another
// call).
func nodeView(n *flowNodeMeta) map[string]any {
	if n == nil {
		return map[string]any{}
	}
	v := map[string]any{
		"id":       n.ID,
		"type":     n.Type,
		"position": map[string]int{"x": n.Position.X, "y": n.Position.Y},
	}
	if n.ParentNode != "" {
		v["parent_node"] = n.ParentNode
	}
	return v
}

// argNodePosition parses update_node's position argument ({x, y}; coordinates of a child node are relative to its parent).
func argNodePosition(args map[string]any) (map[string]int, bool, error) {
	raw, exists := args["position"]
	if !exists || raw == nil {
		return nil, false, nil
	}
	pos, err := parseStepPosition(raw, "position")
	if err != nil {
		return nil, false, err
	}
	return pos, true, nil
}

// handlesView lists the handles available for a type, fed straight into create_edge so that the model need not guess the
// positions.
func handlesView(typ string) map[string]any {
	rule := nodeHandleRules[typ]
	out := map[string]any{
		"in":  append([]string{}, rule.in...),
		"out": append([]string{}, rule.out...),
	}
	if typ == "branch" || typ == "intent" {
		out["children_out"] = append([]string{}, branchChildOut...)
		out["children_handle"] = "source<config.children[].id>left|right"
	}
	return out
}

func creatableTypeList() string {
	names := make([]string, 0, len(creatableNodeTypes))
	for _, t := range []string{
		"llm", "code", "http", "mcp", "rpc", "branch", "intent", "loop", "process", "function",
		"call", "assign", "memory", "raise", "result", "progress", "break", "continue",
		"return", "exit", "layout", "comment",
	} {
		if creatableNodeTypes[t] {
			names = append(names, t)
		}
	}
	return strings.Join(names, " / ")
}

// buildNodeForTool is the shared pre-check and creation step of the node tools (including the entry a container brings
// automatically).
// It returns the new node id, the new container's entry id, an entry added to the parent container, and warnings.
func buildNodeForTool(doc *flowDoc, typ, label, parentID string, userCfg map[string]any, member bool) (id, entryID, parentEntryID string, warnings []string, err error) {
	if typ == "" {
		return "", "", "", nil, errors.New("type must not be empty")
	}
	if !creatableNodeTypes[typ] {
		hint := "start is generated by create_flow, entry comes with the container"
		if typ == "knowledge" {
			hint = "knowledge has no executor on the backend (wiring it in only fails with no executor registered) and is kept for rendering existing diagrams; " +
				"for knowledge retrieval call the matching service from an mcp / rpc node, or let the llm node carry the context"
		}
		return "", "", "", nil, fmt.Errorf("cannot create a node of type %q. Creatable types: %s (%s)", typ, creatableTypeList(), hint)
	}
	if parentID != "" {
		p, ok := doc.node(parentID)
		if !ok {
			return "", "", "", nil, fmt.Errorf("parent_node %q does not exist: take the id from diagram.nodes[].id in read_flow", parentID)
		}
		if !containerTypes[p.Type] {
			return "", "", "", nil, fmt.Errorf("parent_node %q is %s and cannot hold children: only loop / process / function are containers", parentID, p.Type)
		}
	}
	if typ == "function" && parentID != "" {
		return "", "", "", nil, errors.New("a function node can only be created at the top level: call nodes invoke it through config.target and it takes no edges")
	}
	// Membership is a property of a host body: a node outside process / loop has no scope to dispatch it, and the runtime
	// rejects the flag with a config error. Refused at the write, like every other structural rule here.
	if member {
		parentType := ""
		if parentID != "" {
			if p, ok := doc.node(parentID); ok {
				parentType = p.Type
			}
		}
		if parentType != "process" && parentType != "loop" {
			return "", "", "", nil, fmt.Errorf(
				"concurrent=true needs parent_node to be a process or loop: only a container body is a concurrency scope (parent %q)", parentID)
		}
		if typ == "function" {
			return "", "", "", nil, errors.New("a function node cannot be a concurrent member: it is invoked by a call, not by the body's chain")
		}
		if !flowcheck.CanBeConcurrentMember(typ) {
			return "", "", "", nil, fmt.Errorf(
				"a %s node cannot be a concurrent member: control flow stays on the body's chain, output keeps its place on it, and a step that never waits gains nothing from a slot", typ)
		}
	}
	if typ == "return" && !doc.isOrInside(parentID, "function") {
		return "", "", "", nil, errors.New("a return node can only be created inside a function container (a direct child or deeper)")
	}
	// break / continue need a loop above them: the node itself fails at run time otherwise (control.go checkSignalScope), and
	// flowcheck reports control_scope - so the write boundary refuses it instead of storing a broken step.
	if typ == "break" || typ == "continue" {
		switch doc.loopScope(parentID) {
		case "loop":
		case "function":
			return "", "", "", nil, fmt.Errorf("a %s node cannot live inside a function body: a function is an isolation scope, so declare the loop inside that function", typ)
		default:
			return "", "", "", nil, fmt.Errorf("a %s node can only be created inside a loop: with none above it the run fails with a config error", typ)
		}
	}

	cfg := defaultNodeConfig(typ, doc.newNodeID)
	if cfg == nil {
		cfg = map[string]any{}
	}
	for k, v := range userCfg {
		cfg[k] = v
	}
	// A loop publishes a different set of variables per mode: filling them here is what makes the condition script in a while
	// / do_while node able to read anything at all.
	if typ == "loop" {
		applyLoopVars(cfg)
	}
	// The types that read no inputs (process, function, call, …) get the block dropped instead of stored.
	if w := applyInputsPolicy(cfg, typ, "new node"); w != "" {
		warnings = append(warnings, w)
	}
	// branch / intent children may be supplied by the caller; when they are, every entry must end up with an id.
	normalizeBranchChildren(doc, typ, cfg)
	// References written as a label become node ids before the config is stored (the same rule create_flow applies).
	doc.resolveRefsInConfig(cfg)

	label = strings.TrimSpace(label)
	if label != "" {
		if owner := doc.labelOwner(label); owner != "" {
			return "", "", "", nil, fmt.Errorf(
				"label %q is already used by node %s: node labels must be unique across the flow"+
					" (source_ref / call.target can both be written as labels, and a duplicate points at the wrong node); pick another one, or leave it empty so the tool adds a suffix",
				label, owner)
		}
	} else {
		label = doc.uniqueLabel(defaultNodeLabel(typ))
	}

	ws, err := validateStepConfig(typ, cfg)
	if err != nil {
		return "", "", "", nil, err
	}
	warnings = append(warnings, ws...)

	id = doc.newNodeID()
	// A top-level function does not continue the main row: it is entered by a call, not by an edge, so it goes below the
	// whole graph instead (the same place the auto layout puts it).
	pos := doc.positionFor(parentID)
	if typ == "function" && parentID == "" {
		pos = doc.positionBelowFlow()
	}
	raw, err := buildNodeJSON(id, typ, label, cfg, parentID, pos, member)
	if err != nil {
		return "", "", "", nil, err
	}
	if err := doc.addNode(raw); err != nil {
		return "", "", "", nil, err
	}

	// When the parent container has no entry, add one on the way: otherwise this new child can never run (the executor returns
	// success straight away).
	if parentID != "" && !doc.hasEntryOf(parentID) {
		pid := doc.newNodeID()
		praw, err := buildNodeJSON(pid, "entry", doc.uniqueLabel("Entry"), nil, parentID, map[string]int{"x": childBaseX, "y": childBaseY}, false)
		if err != nil {
			return "", "", "", nil, err
		}
		if err := doc.addNode(praw); err != nil {
			return "", "", "", nil, err
		}
		parentEntryID = pid
		warnings = append(warnings, fmt.Sprintf("container %q had no entry, so one was added (id=%s): a container without an entry succeeds but runs nothing", parentID, pid))
	}

	if containerTypes[typ] {
		entryID = doc.newNodeID()
		eraw, err := buildNodeJSON(entryID, "entry", doc.uniqueLabel("Entry"), nil, id, map[string]int{"x": childBaseX, "y": childBaseY}, false)
		if err != nil {
			return "", "", "", nil, err
		}
		if err := doc.addNode(eraw); err != nil {
			return "", "", "", nil, err
		}
	}
	return id, entryID, parentEntryID, warnings, nil
}

// hasEntryOf reports whether a container already has an entry child.
func (d *flowDoc) hasEntryOf(parentID string) bool {
	for i := range d.nodes {
		if d.nodes[i].ParentNode == parentID && d.nodes[i].Type == "entry" {
			return true
		}
	}
	return false
}

// labelOwner returns the id of the node currently using that label ("" = unused).
//
// label is the writable form of source_ref / call.target, and a duplicate would make those references point at the wrong node,
// so labels must be unique across the whole flow graph.
func (d *flowDoc) labelOwner(label string) string {
	label = strings.TrimSpace(label)
	if label == "" {
		return ""
	}
	for i := range d.nodes {
		if strings.TrimSpace(d.nodes[i].Data.Label) == label {
			return d.nodes[i].ID
		}
	}
	return ""
}

// resolveRefsInConfig rewrites node references written as a label into node ids, for the config of one node:
// config.inputs.*.source_ref, config.targets.*.source_ref, config.args.*.source_ref and config.target.
//
// create_flow resolves a whole diagram at once (diagramBuilder.resolveSourceRefs / resolveNodeLabels); create_node,
// insert_node and update_node write a single config and resolve it here - otherwise a label passes creation and the run
// then fails to find the node. The same rule as the builder: a value matching an existing node id is left alone, and an
// ambiguous label is not guessed at.
func (d *flowDoc) resolveRefsInConfig(cfg map[string]any) {
	if len(cfg) == 0 {
		return
	}
	byLabel := make(map[string]string, len(d.nodes))
	for i := range d.nodes {
		label := strings.TrimSpace(d.nodes[i].Data.Label)
		if label == "" {
			continue
		}
		if _, dup := byLabel[label]; dup {
			continue
		}
		byLabel[label] = d.nodes[i].ID
	}
	rewrite := func(ref string) string {
		if ref == "" {
			return ref
		}
		if _, ok := d.node(ref); ok {
			return ref
		}
		if id, ok := byLabel[ref]; ok {
			return id
		}
		return ref
	}
	for _, section := range []string{"inputs", "targets", "args"} {
		for _, raw := range objectOf(cfg[section]) {
			def := objectOf(raw)
			if def == nil {
				continue
			}
			if ref, ok := def["source_ref"].(string); ok {
				def["source_ref"] = rewrite(ref)
			}
		}
	}
	if ref, ok := cfg["target"].(string); ok {
		cfg["target"] = rewrite(ref)
	}
}

// uniqueLabel appends -2 / -3 ... to an **auto-generated** label until it is unique in the graph.
// A label the user wrote explicitly that collides is an error, never silently renamed.
func (d *flowDoc) uniqueLabel(base string) string {
	base = strings.TrimSpace(base)
	if base == "" {
		base = "Node"
	}
	if d.labelOwner(base) == "" {
		return base
	}
	for i := 2; i <= 999; i++ {
		if candidate := fmt.Sprintf("%s-%d", base, i); d.labelOwner(candidate) == "" {
			return candidate
		}
	}
	return fmt.Sprintf("%s-%d", base, len(d.nodes)+1)
}

// normalizeBranchChildren: the children of branch / intent must carry an id (the executor uses it to find outgoing edges).
func normalizeBranchChildren(doc *flowDoc, typ string, cfg map[string]any) {
	if typ != "branch" && typ != "intent" {
		return
	}
	kids, _ := cfg["children"].([]any)
	if len(kids) == 0 {
		cfg["children"] = []any{map[string]any{"id": doc.newNodeID(), "label": "Branch 1", "condition": "", "exclusive": true}}
		return
	}
	for _, k := range kids {
		m, ok := k.(map[string]any)
		if !ok {
			continue
		}
		if id, _ := m["id"].(string); strings.TrimSpace(id) == "" {
			m["id"] = doc.newNodeID()
		}
	}
	cfg["children"] = kids
}

