func (t *insertNodeTool) Execute(ctx context.Context, c *Context, args map[string]any) (any, error) {
	doc, detail, err := loadFlowDoc(ctx, c, argString(args, "flow"))
	if err != nil {
		return nil, err
	}
	edgeID := strings.TrimSpace(argString(args, "edge_id"))
	if edgeID == "" {
		return nil, errors.New("edge_id must not be empty (diagram.edges[].id from read_flow)")
	}
	idx := doc.edgeIndex(edgeID)
	if idx < 0 {
		return nil, fmt.Errorf("no edge with edge_id=%q: check diagram.edges with read_flow first", edgeID)
	}
	old := doc.edges[idx]
	if old.SourceHandle == "" || old.TargetHandle == "" {
		return nil, fmt.Errorf("edge %s has no source_handle / target_handle and cannot be split: fill them in with update_edge first", edgeID)
	}
	src, ok := doc.node(old.Source)
	if !ok {
		return nil, fmt.Errorf("edge %s has a source node %q that does not exist", edgeID, old.Source)
	}

	typ := strings.ToLower(strings.TrimSpace(argString(args, "type")))
	userCfg, err := argObject(args, "config")
	if err != nil {
		return nil, err
	}
	if creatableNodeTypes[typ] {
		if err := checkInsertableType(typ); err != nil {
			return nil, err
		}
	}
	nodeID, entryID, parentEntryID, warnings, err := buildNodeForTool(
		doc, typ, strings.TrimSpace(argString(args, "label")), src.ParentNode, userCfg, argBool(args, "concurrent"),
	)
	if err != nil {
		return nil, err
	}

	inPos := pickHandle(nodeHandleRules[typ].in, []string{"left", "top", "right", "bottom"})
	outPos := pickHandle(nodeHandleRules[typ].out, []string{"right", "bottom", "left"})

	head := flowEdge{
		Source:       old.Source,
		Target:       nodeID,
		SourceHandle: old.SourceHandle,
		TargetHandle: "target" + nodeID + inPos,
	}
	tail := flowEdge{
		Source:       nodeID,
		Target:       old.Target,
		SourceHandle: "source" + nodeID + outPos,
		TargetHandle: old.TargetHandle,
	}
	// Remove the old edge before validating: otherwise it collides with "at most one edge per node pair" / "one edge per
	// outlet".
	doc.removeEdge(edgeID)
	if _, err := doc.validateEdge(head, ""); err != nil {
		return nil, fmt.Errorf("the leading edge after the insert is invalid: %w", err)
	}
	if _, err := doc.validateEdge(tail, ""); err != nil {
		return nil, fmt.Errorf("the trailing edge after the insert is invalid: %w", err)
	}
	head.ID = doc.newEdgeID()
	tail.ID = doc.newEdgeID()
	doc.edges = append(doc.edges, head, tail)

	info, err := saveDiagram(ctx, c, detail, doc)
	if err != nil {
		return nil, err
	}
	n, _ := doc.node(nodeID)
	out := map[string]any{
		"flow_id":    info.ID,
		"flow_name":  info.Name,
		"node":       nodeView(n),
		"edges":      []any{edgeView(head), edgeView(tail)},
		"handles":    handlesView(typ),
		"edge_count": len(doc.edges),
	}
	if entryID != "" {
		out["entry"] = map[string]any{"id": entryID, "parent_node": nodeID}
	}
	if parentEntryID != "" {
		out["parent_entry"] = map[string]any{"id": parentEntryID}
	}
	if len(warnings) > 0 {
		out["warnings"] = warnings
	}
	return out, nil
}

// checkInsertableType: a node spliced into the middle of a chain needs both an incoming and an outgoing edge.
func checkInsertableType(typ string) error {
	rule := nodeHandleRules[typ]
	if len(rule.in) == 0 {
		return fmt.Errorf("a %s node has no incoming handle and cannot be inserted mid-chain (create top-level nodes with create_node)", typ)
	}
	if len(rule.out) == 0 {
		return fmt.Errorf("a %s node has no outgoing handle and cannot be inserted mid-chain (wire terminal nodes to the chain tail with create_edge)", typ)
	}
	return nil
}

func pickHandle(allowed, prefer []string) string {
	for _, p := range prefer {
		if containsStr(allowed, p) {
			return p
		}
	}
	if len(allowed) > 0 {
		return allowed[0]
	}
	return ""
}

// nodeLabelOf reads data.label from a raw node.
func nodeLabelOf(raw json.RawMessage) string {
	var n struct {
		Data struct {
			Label string `json:"label"`
		} `json:"data"`
	}
	_ = json.Unmarshal(raw, &n)
	return strings.TrimSpace(n.Data.Label)
}

// concurrencyBlocks summarises every host body in a diagram: the host, the members it dispatches, its limit and its join
// mode. The walk follows the entry chain and stops where the runner stops (a node outside the host, a branch / intent, or
// a fork in the edges), so a block never claims a member the run would not dispatch.
func concurrencyBlocks(d *flowDoc) []map[string]any {
	type scopeNode struct {
		ID         string `json:"id"`
		Type       string `json:"type"`
		ParentNode string `json:"parent_node"`
		Data       struct {
			Concurrent bool `json:"concurrent"`
			Config     struct {
				Parallel struct {
					MaxConcurrency int    `json:"max_concurrency"`
					Join           string `json:"join"`
				} `json:"parallel"`
			} `json:"config"`
		} `json:"data"`
	}
	nodes := make([]scopeNode, 0, len(d.nodeRaw))
	for _, raw := range d.nodeRaw {
		var n scopeNode
		if err := json.Unmarshal(raw, &n); err != nil || n.ID == "" {
			continue
		}
		nodes = append(nodes, n)
	}
	byID := make(map[string]*scopeNode, len(nodes))
	children := make(map[string][]string, len(nodes))
	for i := range nodes {
		n := &nodes[i]
		byID[n.ID] = n
		if n.ParentNode != "" {
			children[n.ParentNode] = append(children[n.ParentNode], n.ID)
		}
	}
	next := make(map[string]string, len(d.edges))
	multi := make(map[string]bool, len(d.edges))
	for _, e := range d.edges {
		if _, seen := next[e.Source]; seen {
			multi[e.Source] = true
		}
		next[e.Source] = e.Target
	}

	var out []map[string]any
	for i := range nodes {
		host := &nodes[i]
		if host.Type != "process" && host.Type != "loop" {
			continue
		}
		child := make(map[string]bool, len(children[host.ID]))
		cur := ""
		for _, c := range children[host.ID] {
			child[c] = true
			if byID[c] != nil && byID[c].Type == "entry" {
				cur = next[c]
			}
		}
		members := []string{}
		seen := make(map[string]bool)
		for cur != "" && child[cur] && !seen[cur] {
			seen[cur] = true
			n := byID[cur]
			if n == nil {
				break
			}
			if n.Data.Concurrent {
				members = append(members, n.ID)
			}
			if multi[cur] || n.Type == "branch" || n.Type == "intent" {
				break
			}
			cur = next[cur]
		}
		join := host.Data.Config.Parallel.Join
		if join == "" {
			join = "collect"
		}
		out = append(out, map[string]any{
			"host":            host.ID,
			"members":         members,
			"max_concurrency": host.Data.Config.Parallel.MaxConcurrency,
			"join":            join,
		})
	}
	return out
}

// checkSelfInputReference refuses a config.inputs / config.args entry that reads the node being written: its own outputs
// and locals are empty until it runs, so the reference can never resolve. saveDiagram rejects the finished diagram too, but
// failing here names the entry while the model still has the patch in hand. Matching is by id or exact label - the two
// forms a source_ref accepts; anything this helper cannot resolve is left to saveDiagram.
func checkSelfInputReference(nodeID, label string, cfg map[string]any) error {
	for _, block := range []string{"inputs", "args"} {
		entries, _ := cfg[block].(map[string]any)
		for name, raw := range entries {
			m, _ := raw.(map[string]any)
			if m == nil {
				continue
			}
			if st, _ := m["source_type"].(string); st != "node" {
				continue
			}
			ref, _ := m["source_ref"].(string)
			ref = strings.TrimSpace(ref)
			if ref == "" {
				continue
			}
			if ref == nodeID || (label != "" && ref == label) {
				return fmt.Errorf(
					"%s.%s reads this node's own outputs/locals (%q): they do not exist until the node runs, so the value can never be resolved; read an upstream node or the container's output instead",
					block, name, ref)
			}
		}
	}
	return nil
}

