func (t *createFlowTool) Execute(ctx context.Context, c *Context, args map[string]any) (any, error) {
	name := strings.TrimSpace(argString(args, "name"))
	if err := validateFlowName(name); err != nil {
		return nil, err
	}
	// description is required: the admin side's "update workflow" refuses an empty one, and creating a flow that cannot be
	// updated is a landmine.
	description := strings.TrimSpace(argString(args, "description"))
	if description == "" {
		return nil, errors.New("description must not be empty: the list uses it to tell flows apart, and the front-end editor requires it")
	}
	arguments, argNames, err := parseFlowArguments(args["arguments"])
	if err != nil {
		return nil, err
	}
	if c.Flows == nil {
		return nil, errors.New("flow manager not available")
	}
	exists, err := c.Flows.Exists(ctx, name)
	if err != nil {
		return nil, err
	}
	if exists {
		return nil, fmt.Errorf("workflow %q already exists: pick another name or inspect it with read_flow", name)
	}

	steps, err := parseFlowSteps(args["steps"])
	if err != nil {
		return nil, err
	}
	concurrency, err := parseConcurrencyPolicy(args)
	if err != nil {
		return nil, err
	}
	build, err := buildFlowDiagram(steps, concurrency)
	if err != nil {
		return nil, err
	}
	endpoints, err := parseFlowEndpoints(args)
	if err != nil {
		return nil, err
	}

	id, err := c.Flows.Create(ctx, FlowInput{
		Name:        name,
		Description: description,
		Diagram:     build.Diagram,
		Arguments:   arguments,
		Endpoints:   endpoints,
	})
	if err != nil {
		return nil, err
	}
	// Field names stay consistent with the other flow tools (flow_id / flow_name): create_flow used id / name earlier, which
	// forced callers to remember two sets, whereas the node, edge and run bodies all say flow_id - so this follows suit.
	out := map[string]any{
		"flow_id":   id,
		"flow_name": name,
		"steps":     len(steps),
		"nodes":     nodeOutlines(build.Nodes),
		"endpoints": endpoints,
	}
	if len(argNames) > 0 {
		// Echo the parameter names rather than the whole schema: what needs verifying is "which ones were declared", and the raw
		// text is available through read_flow.
		out["arguments"] = argNames
	}
	// Structural gaps (a container with no children, a sub-branch with no outgoing edge, ...) do not block creation, but the
	// caller must see them - otherwise "created" and "runnable" get conflated.
	if len(build.Warnings) > 0 {
		out["warnings"] = build.Warnings
	}
	return out, nil
}

// nodeOutlines reduces the nodes to a {id, type, label, position} list.
//
// It goes back to create_flow so the model can verify everything id-related: who source_ref points at, which node heads a branch
// sub-chain, what call's target should be. There is no update_flow, so a wrong build can only be deleted and rebuilt.
// position is included so the model can judge whether the automatic layout is acceptable and fine-tune with update_node when
// needed.
func nodeOutlines(nodes []diagramNode) []map[string]any {
	out := make([]map[string]any, 0, len(nodes))
	for _, n := range nodes {
		label, _ := n.Data["label"].(string)
		out = append(out, map[string]any{
			"id": n.ID, "type": n.Type, "label": label, "position": n.Position,
		})
	}
	return out
}

