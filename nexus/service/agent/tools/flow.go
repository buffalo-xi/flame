// filterFlowRunNodes filters nodes by only_failed / nodes; NodeTotal keeps the count from before filtering, so the caller does not
// think "this is all the nodes the flow ran".
func filterFlowRunNodes(detail *FlowRunDetail, onlyFailed bool, wanted []string) {
	set := make(map[string]struct{}, len(wanted))
	for _, id := range wanted {
		if id = strings.TrimSpace(id); id != "" {
			set[id] = struct{}{}
		}
	}
	kept := make([]FlowRunNode, 0, len(detail.Nodes))
	for _, n := range detail.Nodes {
		if len(set) > 0 {
			if _, ok := set[n.NodeID]; !ok {
				continue
			}
		}
		if onlyFailed && n.Status != "failed" {
			continue
		}
		kept = append(kept, n)
	}
	detail.Nodes = kept
}

// flowRunVarLimit is the return cap (in bytes) for one variable field. Storage already truncates at 64KB per top-level key, but
// one run can have dozens of nodes x 4 fields, and returning them all is megabytes.
const flowRunVarLimit = 8 * 1024

// clipFlowRunDetail clips read_flow_run's result: output / logs / stacks are cut as text, variables degrade to a JSON summary.
func clipFlowRunDetail(detail *FlowRunDetail, limit int) {
	if limit <= 0 {
		limit = DefaultMaxOutput
	}
	if clipped := cutHeadBytes(detail.Result, limit); clipped != detail.Result {
		detail.Result = clipped
		detail.Truncated = true
	}
	var clipped bool
	detail.RunArgs, clipped = clipVar(detail.RunArgs, flowRunVarLimit)
	detail.Truncated = detail.Truncated || clipped
	detail.FlowVars, clipped = clipVar(detail.FlowVars, flowRunVarLimit)
	detail.Truncated = detail.Truncated || clipped
	for i := range detail.Nodes {
		n := &detail.Nodes[i]
		if clippedText := cutTailBytes(n.ErrStack, flowRunNodeLogLimit); clippedText != n.ErrStack {
			n.ErrStack = clippedText
			detail.Truncated = true
		}
		if clippedText := cutTailBytes(n.Logs, flowRunNodeLogLimit); clippedText != n.Logs {
			n.Logs = clippedText
			detail.Truncated = true
		}
		for _, field := range []struct {
			dst *any
			src any
		}{
			{&n.InputVars, n.InputVars},
			{&n.OutputVars, n.OutputVars},
			{&n.LocalVars, n.LocalVars},
			{&n.Extra, n.Extra},
		} {
			clippedField, changed := clipVar(field.src, flowRunVarLimit)
			*field.dst = clippedField
			detail.Truncated = detail.Truncated || changed
		}
	}
}

// clipVar replaces an over-limit variable value with a "size + top-level key list" summary.
//
// It cannot be cut at N bytes like text: these values are JSON objects, and half of one is not valid JSON, so the outer
// serialisation fails outright (the whole tool result becomes an error). A summary is valid and still conveys "the keys are all
// here, the values are too large".
func clipVar(v any, limit int) (any, bool) {
	if v == nil || limit <= 0 {
		return v, false
	}
	b, err := json.Marshal(v)
	if err != nil || len(b) <= limit {
		return v, false
	}
	summary := map[string]any{"_truncated": true, "_bytes": len(b)}
	if m, ok := v.(map[string]any); ok {
		keys := make([]string, 0, len(m))
		for k := range m {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		summary["keys"] = keys
	}
	return summary, true
}

// cutHeadBytes keeps the head up to a byte limit and backs off to a rune boundary:
// cutting []byte directly splits a multi-byte character in half, which JSON serialisation turns into U+FFFD.
func cutHeadBytes(s string, limit int) string {
	if limit <= 0 || len(s) <= limit {
		return s
	}
	i := limit
	for i > 0 && !utf8.RuneStart(s[i]) {
		i--
	}
	return s[:i] + "\n… (truncated)"
}

// cutTailBytes is the same, but keeps the tail.
func cutTailBytes(s string, limit int) string {
	if limit <= 0 || len(s) <= limit {
		return s
	}
	i := len(s) - limit
	for i < len(s) && !utf8.RuneStart(s[i]) {
		i++
	}
	return "… (truncated, tail kept)\n" + s[i:]
}

