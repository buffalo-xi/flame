// ===== Workflows ({schema}.flows) =====
//
// The same shape as the agent meta tools: create / delete / list / read / run (a test run) / read_flow_run (read a run
// record), category flow-admin (super agent only).
// The difference is that a workflow has **no definition-domain directory** - the entity is one JSONB row in the flows table
// (diagram + variables + limits), so create_flow has to assemble the "step list" into a diagram the frontend can render and the
// executor can run.
//
// Why the model is not asked to pass a diagram directly: the 26 node types each have their own config shape, plus coordinates,
// edges and source_handle / target_handle. Hand-writing that JSON costs one wrong field and you get "it renders, it crashes on
// run". The tool exposes only the "linear steps" layer; the diagram is generated by buildLinearDiagram.

// FlowStep is one step when creating a workflow.
type FlowStep struct {
	Type   string         // node type, see flowStepTypes
	Label  string         // node title (the short name shown on the canvas)
	Config map[string]any // node config, which differs per type and is written into data.config as is
	// Position is optional: canvas coordinates laid out by the model itself.
	//
	// The rule is "top-level nodes all or none": give all of them and the layout follows yours exactly, with the tool only
	// checking for overlaps; miss one and the whole thing falls back to automatic layout - half a set of coordinates mixed with
	// automatic layout only makes them overlap each other.
	// Container children are not given (their coordinates are relative to the parent, and the tool lays them out vertically).
	Position map[string]int
	// Branches only matters for branch / intent: declare a step chain per sub-branch of the node.
	//
	// The executor routes by handle (executors.findBranchEdge prefix-matches "source"+branchID), so "a branch can actually
	// split" means every config.children[].id has an outgoing edge hanging off source<that id>.
	// Once declared here, each sub-chain gets an edge with that handle pulled from the branch node.
	//
	// A step that declares Branches must be the last one in its chain: a branch only walks the default edge when it is done,
	// "the main chain after the branch" has no meaning, and later steps belong inside the sub-chains.
	Branches []FlowBranch

	// Children only matters for loop / process / function: the step chain inside the container.
	//
	// The executor starts from the entry node whose parent_node is the container id, so the tool creates that entry on the way
	// and wires the first Children step to it - without that step the container "succeeds while running nothing".
	// Unlike Branches, a step with Children does not have to be the end of the chain: a container has a normal inlet and outlet.
	Children []FlowStep
}

// FlowBranch is the step chain of one sub-branch on a branch node.
//
// Key corresponds to config.children[].id; "default" is the default branch (the edge taken when no condition matches - the
// executor finds it by "source"+the node's own id, so it does not need an extra entry in children).
//
// A slice rather than a map: node ids are allocated in declaration order, and a map's random iteration order would build a
// different diagram from the same input.
type FlowBranch struct {
	Key   string
	Steps []FlowStep
}

// FlowInfo is one row returned by list_flows.
type FlowInfo struct {
	ID          string   `json:"id"`
	Name        string   `json:"name"`
	Description string   `json:"description"`
	Status      int      `json:"status"`
	Endpoints   []string `json:"endpoints,omitempty"` // protocols it is exposed on (mcp / rpc)
}

// FlowDetail is what read_flow returns: metadata + diagram + the entry argument declaration.
//
// Arguments is the raw flows.arguments (JSON Schema shape); it is omitted when nothing was declared, so the model can tell
// "there are no inputs" from "there are inputs but they cannot be read".
type FlowDetail struct {
	FlowInfo
	Diagram   json.RawMessage `json:"diagram"`
	Arguments json.RawMessage `json:"arguments,omitempty"`
}

// FlowInput is the input of workflow creation (the diagram has already been assembled by the tool layer).
type FlowInput struct {
	Name        string
	Description string
	Diagram     json.RawMessage
	// Arguments is the entry argument declaration (flows.arguments); empty = none declared.
	// Once exposed it is the endpoint's input_schema and also the inputs key of run_flow.
	Arguments json.RawMessage
	Endpoints []string // which protocols to expose it on; empty = internal only
}

// flowRefHint is the shared description of the flow / workflow locator argument (used by read / delete / run).
//
// Two deliberate choices in the wording:
//   - the example gives a name only, never a UUID. Models imitate strongly, and a uuid in the example teaches it to invent ids;
//     an invented id is well-formed, can only be caught by "not found", and is the hardest class of error to self-heal;
//   - it says outright "never invent an id", compressing "the id must come from list_flows" into one actionable sentence.
const flowRefHint = "Workflow name, e.g. daily-sales-report. " +
	"The id returned by list_flows is accepted too (the two are equivalent: a UUID-shaped value is looked up by id, anything else by name); " +
	"never invent an id — copy it from list_flows' output"

// FlowRunResult is the result of one test run (the body returned by run_flow).
//
// It answers only "did it run, where did it stop, why", and **returns no node output variables**: an HTTP body / LLM text is
// routinely tens of KB, which is expensive in the model context and nearly unreadable; the run record page and read_flow are
// there to look at the data.
type FlowRunResult struct {
	FlowID   string `json:"flow_id"`
	FlowName string `json:"flow_name"`
	RunID    string `json:"run_id"`
	// Status: success / failed / cancelled (the same values as flow_run_records.status).
	Status     string `json:"status"`
	ErrCode    string `json:"err_code,omitempty"` // the error code of the earliest failing node
	ErrMsg     string `json:"err_msg,omitempty"`
	Result     string `json:"result,omitempty"` // the final output (the result node / what return collected)
	DurationMs int64  `json:"duration_ms"`
	// Nodes are the nodes that ran, in ascending start time. Successful ones are included too - on a failure they show how far
	// it got.
	Nodes     []FlowNodeTrace `json:"nodes"`
	Truncated bool            `json:"truncated,omitempty"` // Result / node logs were truncated
}

// FlowNodeTrace is the execution result of a single node.
type FlowNodeTrace struct {
	NodeID     string `json:"node_id"`
	Type       string `json:"type,omitempty"`
	Status     string `json:"status"` // success / failed / skipped / cancelled
	ErrCode    string `json:"err_code,omitempty"`
	ErrMsg     string `json:"err_msg,omitempty"`
	DurationMs int64  `json:"duration_ms"`
	// Logs / ErrStack / PostError are only given for non-successful nodes (script stderr, traceback, variable lookup errors -
	// the diagnostic material); a successful node's log is mostly noise such as "executed successfully", and returning it only
	// wastes context.
	Logs string `json:"logs,omitempty"`
	// ErrStack is far longer than ErrMsg but the most useful for locating a failure: lua / python / js tracebacks live here
	// only.
	ErrStack string `json:"err_stack,omitempty"`
	// PostError is an error from the post-processing script (post): it does not affect the node's main status, but it is still
	// one of the failure causes.
	PostError  string `json:"post_error,omitempty"`
	RetryCount int    `json:"retry_count,omitempty"`
}

// FlowRunDetail is the body of read_flow_run: one run record + the node records (including node-level variables).
//
// The split with FlowRunResult: that one is "the verdict right after a run", this one is "the post-mortem" - variables, error
// stacks and logs are all in the database and remain queryable after the run ends, and not only for the run started by
// run_flow (a frontend debug run, or one started by another agent, has a run_id too).
type FlowRunDetail struct {
	FlowID     string `json:"flow_id"`
	RunID      string `json:"run_id"`
	Status     string `json:"status"`
	RunType    string `json:"run_type,omitempty"` // call / debug / task
	ErrMsg     string `json:"err_msg,omitempty"`
	Result     string `json:"result,omitempty"`
	DurationMs int64  `json:"duration_ms"`
	StartedAt  string `json:"started_at,omitempty"`
	FinishedAt string `json:"finished_at,omitempty"`
	// RunArgs / FlowVars are the run inputs and the flow variable snapshot (decoded into objects, directly readable)
	RunArgs  any `json:"run_args,omitempty"`
	FlowVars any `json:"flow_vars,omitempty"`
	// NodeTotal is the total node count in the record; Nodes may be fewer because of the only_failed / nodes filters
	NodeTotal int           `json:"node_total"`
	Nodes     []FlowRunNode `json:"nodes"`
	Truncated bool          `json:"truncated,omitempty"`
}

// FlowRunNode is one node run record.
type FlowRunNode struct {
	NodeID      string `json:"node_id"`
	Type        string `json:"type,omitempty"`
	Status      string `json:"status"`
	ErrCode     string `json:"err_code,omitempty"`
	ErrMsg      string `json:"err_msg,omitempty"`
	ErrStack    string `json:"err_stack,omitempty"`
	RetryCount  int    `json:"retry_count,omitempty"`
	ErrorAction string `json:"error_action,omitempty"`
	DurationMs  int64  `json:"duration_ms"`
	// The three variable fields come from the stored jsonb and are decoded into objects; over the limit they degrade into a
	// {_truncated, _bytes, keys} summary.
	InputVars  any    `json:"input_vars,omitempty"`
	OutputVars any    `json:"output_vars,omitempty"`
	LocalVars  any    `json:"local_vars,omitempty"`
	Extra      any    `json:"extra,omitempty"` // type-specific results (HTTP status, LLM token usage, ...)
	Logs       string `json:"logs,omitempty"`
	// Truncated means it was already truncated when stored - re-reading will not reveal the whole value, so do not conclude
	// "these are all the values there are".
	Truncated bool `json:"truncated,omitempty"`
}

// FlowsManager registers and queries workflows (injected by service/agent; it carries the tenant schema and repository).
// The same convention as AgentManager: identity and schema are pinned inside the implementation and cannot be passed in from
// the tool layer.
type FlowsManager interface {
	Exists(ctx context.Context, name string) (bool, error)
	Create(ctx context.Context, in FlowInput) (string, error)
	List(ctx context.Context) ([]FlowInfo, error)
	// Get fetches by id or name; id wins, and both empty is an error.
	Get(ctx context.Context, id, name string) (*FlowDetail, error)
	// UpdateDiagram replaces only the diagram (used by create_edge / update_edge / delete_edge): name, description, limits and
	// breakpoints are untouched. id first, name as fallback; not found returns (nil, nil).
	UpdateDiagram(ctx context.Context, id, name string, diagram json.RawMessage) (*FlowInfo, error)
	// UpdateArguments replaces only the entry argument declaration (used by update_flow_arguments): name, description, diagram
	// and limits are untouched. id first, name as fallback; not found returns (nil, nil).
	UpdateArguments(ctx context.Context, id, name string, arguments json.RawMessage) (*FlowInfo, error)
	// Delete removes by id or name and returns the deleted row (for the caller to echo back); not found returns (nil, nil).
	Delete(ctx context.Context, id, name string) (*FlowInfo, error)
	// RunTest test-runs a saved workflow (real execution).
	//
	// callDepth is the calling agent's current stack depth and is passed down as +1 - if the flow contains an agent node,
	// the agent -> flow -> agent cycle is bounded by it. A non-empty sessionID puts the flow in the same session venue as the
	// caller.
	// followDrafts decides whether sub-flows started by this run read the draft or the released version (the same semantics as
	// the debugger switch of the same name on the editor page).
	// Not found returns (nil, nil) and the caller reports "not found".
	RunTest(ctx context.Context, ref string, args map[string]any, sessionID string, callDepth int, followDrafts bool) (*FlowRunResult, error)
	// GetRun reads one run record (the run plus all node records, with variables and error stacks).
	// Not found returns (nil, nil) and the caller reports "not found".
	GetRun(ctx context.Context, runID string) (*FlowRunDetail, error)
}

// flowStepTypes are the node types allowed in steps, matching the executors.RegisterExecutor registry one to one.
//
// Excluded are the front-end structural / visual nodes: start (the tool generates id=1 itself), entry (the container inlet,
// generated by the frontend), comment / knowledge (no executor - wiring them into a chain reports no executor registered), and
// layout (a placeholder the runner skips straight through, but the tool does not create it).
//
// "Allowed to create" is not the same as "runs once wired linearly": branch / intent need several outgoing edges with handles,
// loop / process / function need children, wait needs a fork on the same chain, and call's target must point at an existing
// function node id. Those structural gaps do not block creation, but they are returned as warnings so the caller knows where to
// fill them in (the frontend canvas).
var flowStepTypes = map[string]bool{
	// Executing types: one in, one out, runnable when wired linearly
	"llm": true, "code": true, "http": true, "mcp": true, "rpc": true,
	"assign": true, "memory": true, "result": true, "progress": true,
	// Control flow / containers: creatable, but need extra structure (see flowStepHint)
	"branch": true, "intent": true, "loop": true, "process": true, "function": true,
	"call": true, "wait": true, "fork": true,
	// Control signals: they end the flow early and usually do not belong on the main chain
	"break": true, "continue": true, "return": true, "exit": true,
	// Visual nodes: layout is skipped straight through by the runner, which makes it a good "wrap point / grouping anchor" to
	// use the main chain's height; comment / knowledge have no executor and knowledge errors out, so they stay closed.
	"layout": true,
}

// flowStepHint points out "why this node will not do anything in a linear graph"; an empty string = no hint.
// It only hints, never blocks: the node itself is legal, it merely lacks structure, which the user can add on the canvas.
func flowStepHint(typ, id string, idx int) string {
	switch typ {
	case "branch", "intent":
		return fmt.Sprintf("step %d (%s, id=%s) has no branches: it only has the main-chain outgoing edge, and the executor cannot route by source<sub-branch id>, "+
			"so every condition is skipped (the default branch is not taken either). For conditional routing, write branches on this step: each key maps to "+
			"config.children[].id and its value is that branch's own step chain; use key=\"default\" for the unconditional fallback", idx+1, typ, id)
	case "loop", "process", "function":
		return fmt.Sprintf("step %d (%s, id=%s) is a container node and a linear graph has no children — it spins empty at run time; "+
			"nested nodes can only be dragged into the container (entry included) on the front-end canvas", idx+1, typ, id)
	case "wait":
		return fmt.Sprintf("step %d (wait, id=%s) waits on a fork group, but a linear graph has no group members; "+
			"wait's config.fork_node_id and each member's config.concurrency have to be set explicitly", idx+1, id)
	case "break", "continue", "return", "exit":
		return fmt.Sprintf("step %d (%s, id=%s) is a control signal: on the main chain it ends or jumps the rest of the flow right at this step — "+
			"confirm this is the effect you want", idx+1, typ, id)
	}
	return ""
}

type diagramNode struct {
	ID       string         `json:"id"`
	Type     string         `json:"type"`
	Position map[string]int `json:"position"`
	// ParentNode only appears on container children (the inside of loop / process / function)
	ParentNode string `json:"parent_node,omitempty"`
	// Extent keeps a child inside its parent's bounds on the canvas; the value matches the frontend nodeFactory
	Extent map[string]any `json:"extent,omitempty"`
	Data   map[string]any `json:"data"`
}

type diagramEdge struct {
	ID           string  `json:"id"`
	Source       string  `json:"source"`
	Target       string  `json:"target"`
	SourceHandle *string `json:"source_handle"`
	TargetHandle *string `json:"target_handle"`
	// keepSourceHandle marks the first edge of a branch sub-chain: its source_handle is a semantic key
	// (source<config.children[].id>right, which the executor prefix-matches to find the edge) and must not be changed when
	// handles are backfilled after layout.
	// An unexported field, so it never reaches the JSON.
	keepSourceHandle bool
}

// diagramBuild is the build result: the raw diagram + structural-gap warnings + the node list.
//
// The node list is returned to create_flow separately: only with the ids can the model verify that source_ref / call target /
// branch handles landed on the intended nodes (there is no update_flow yet, so a wrong build can only be deleted and rebuilt).
type diagramBuild struct {
	Diagram  json.RawMessage
	Warnings []string
	Nodes    []diagramNode
}

// buildFlowDiagram assembles a step list into a diagram: one main chain at the top level, and branch / intent pulling
// handle-bearing sub-chains off themselves per Branches. Coordinates are laid out centrally by layoutDiagram (main chain
// horizontally, one row per branch), and the frontend can drag them freely afterwards - position does not affect execution.
//
// Node ids follow the build order: start is always 1 and every node created after it adds one (the parent first, then its
// sub-chains in branches declaration order). The same input always yields the same ids and edge order.
//
// The Warnings in the result are structural-gap hints (e.g. a container with no children); they do not block creation.
func buildFlowDiagram(steps []FlowStep, concurrency string) (*diagramBuild, error) {
	if len(steps) == 0 {
		return nil, errors.New("steps must not be empty: a workflow needs at least one step")
	}
	b := &diagramBuilder{concurrency: concurrency}
	b.addStart()
	if _, err := b.emitChain(steps, "1", "", 0, ""); err != nil {
		return nil, err
	}
	// Layout: with a full set of model coordinates the layout follows them (it knows better than any rule what the graph is
	// meant to express); only when they are missing or partial does code lay it out (main chain horizontal, branches vertical,
	// containers sized to their content).
	if !b.applyModelPositions() {
		b.layoutDiagram()
	}
	// Handles are written once the coordinates are final: the main chain is on one row -> right->left, branch sub-chains sit
	// bottom-right -> right->top.
	// A branch sub-chain's source_handle is a semantic key and is left as is when backfilled.
	b.fillEdgeHandles()
	b.resolveSourceRefs()
	b.resolveNodeLabels()
	b.warnCalls()

	raw, err := json.Marshal(map[string]any{"nodes": b.nodes, "edges": b.edges})
	if err != nil {
		return nil, err
	}
	return &diagramBuild{Diagram: raw, Warnings: b.warnings, Nodes: b.nodes}, nil
}

// ===== Concurrency policy (off by default) =====
//
// Concurrency is a capability that is only turned on "when the user explicitly asks": generated definitions never write
// config.concurrency, because a concurrent node runs only itself and does not continue along its outgoing edge (a wait has to
// join it), which is entirely different from serial semantics - a model copying one concurrency line from a doc example breaks
// the whole flow.
//
// The two shapes are declared explicitly by the caller (the model, judging from the user's request):
//   - mono  single-node concurrency: one node processes several items concurrently, no group ({"mode":"mono"})
//   - group concurrency group: several nodes run at the same time and a wait joins them ({"mode":"fork","fork_node_id":...})
const (
	concurrencyOff   = "off"
	concurrencyMono  = "mono"
	concurrencyGroup = "group"
)

// concurrencyTypes are the types that can really be configured on the canvas (CodeNode / HttpNode / CallNode carry the
// concurrency dropdown).
// Other executors accept config.concurrency too, but the frontend cannot change it, so no hint is offered for them.
var concurrencyTypes = map[string]bool{"code": true, "http": true, "call": true}

// concurrencyParamSchema is the concurrency argument shared by the node tools (create_node / insert_node).
var concurrencyParamSchema = map[string]any{
	"type": "string",
	"enum": []any{"off", "mono", "group"},
	"description": "Optional: concurrency shape, **omit for off**, pass it only when the user explicitly asks for concurrency. " +
		"mono = single-node concurrency (this node processes several items concurrently; config becomes {\"mode\":\"mono\"}); " +
		"group = concurrency group (this node joins a fork group; config becomes " +
		"{\"mode\":\"fork\",\"fork_node_id\":\"<fork node id>\"}). " +
		"When omitted, config.concurrency is stripped and a warning is returned.",
}

// parseConcurrencyPolicy parses the concurrency argument: off (default) / mono / group.
func parseConcurrencyPolicy(args map[string]any) (string, error) {
	raw := strings.ToLower(strings.TrimSpace(argString(args, "concurrency")))
	switch raw {
	case "", "off", "none", "serial":
		return concurrencyOff, nil
	case "mono", "single":
		return concurrencyMono, nil
	case "group", "fork", "fork-group", "fork_group":
		return concurrencyGroup, nil
	}
	return "", fmt.Errorf("concurrency supports off / mono / group only, got %q"+
		" (off = off by default, mono = single-node concurrency, group = concurrency group)", raw)
}

// concurrencyShape is how a concurrency shape is written in config (for echoing back).
func concurrencyShape(policy string) string {
	switch policy {
	case concurrencyMono:
		return "{\"mode\":\"mono\"}"
	case concurrencyGroup:
		return "{\"mode\":\"fork\",\"fork_node_id\":\"<fork node id>\"}"
	}
	return ""
}

// applyConcurrencyPolicy handles one node's config.concurrency per the policy and returns the echo back to the caller (an
// empty string = untouched).
//
// where locates the node (create_flow passes "step 3", the node tools pass "the new node").
// Containers (loop / process / function) never carry the key: concurrency is an attribute of "a group member".
func applyConcurrencyPolicy(cfg map[string]any, typ, policy, where string) string {
	if cfg == nil {
		return ""
	}
	raw, ok := cfg["concurrency"]
	if !ok || raw == nil {
		// A concurrency shape was declared but the key was not written: without a hint that reads as "I turned it on" while it
		// actually runs serially.
		if policy != concurrencyOff && concurrencyTypes[typ] {
			return fmt.Sprintf("%s (%s) has no config.concurrency: concurrency shape %s was declared, "+
				"so write %s into the node config", where, typ, policy, concurrencyShape(policy))
		}
		return ""
	}
	cc, _ := raw.(map[string]any)
	if len(cc) == 0 {
		delete(cfg, "concurrency")
		return ""
	}
	mode, _ := cc["mode"].(string)
	forkID, _ := cc["fork_node_id"].(string)
	forkID = strings.TrimSpace(forkID)

	if containerTypes[typ] {
		delete(cfg, "concurrency")
		return fmt.Sprintf("%s (%s): config.concurrency ignored — loop / process containers are serial by default, "+
			"concurrency belongs on the member nodes inside the group", where, typ)
	}
	switch policy {
	case concurrencyMono:
		if mode == "mono" && forkID == "" {
			return ""
		}
		delete(cfg, "concurrency")
		return fmt.Sprintf("%s (%s): config.concurrency ignored — only single-node concurrency is on this time "+
			"({\"mode\":\"mono\"}); declare concurrency=group explicitly for a concurrency group", where, typ)
	case concurrencyGroup:
		if mode == "fork" && forkID != "" {
			return ""
		}
		delete(cfg, "concurrency")
		return fmt.Sprintf("%s (%s): config.concurrency ignored — a concurrency group is on this time "+
			"({\"mode\":\"fork\",\"fork_node_id\":\"<fork node>\"}); declare concurrency=mono explicitly for single-node concurrency",
			where, typ)
	default:
		delete(cfg, "concurrency")
		return fmt.Sprintf("%s (%s): config.concurrency ignored — concurrency is off by default and is only generated "+
			"when the user explicitly asks for it (single-node concurrency=mono, concurrency group=group)", where, typ)
	}
}

// diagramBuilder is the build accumulator: it owns id allocation, edge numbering and warnings.
type diagramBuilder struct {
	nodes    []diagramNode
	edges    []diagramEdge
	seq      int
	warnings []string
	// concurrency is the policy: off (default) / mono / group; the build applies it uniformly to every node's
	// config.concurrency (see applyConcurrencyPolicy).
	concurrency string
	// hasBranches records whether any branch sub-chain was built: it decides how the call id hint reads (k+1 only holds in a
	// purely linear graph)
	hasBranches bool
	// explicit holds the top-level nodes (step.position) whose coordinates the model gave explicitly. When present the layout
	// belongs to the model, and it must be complete - one missing and the whole graph falls back to automatic layout.
	explicit map[string]map[string]int
}

func (b *diagramBuilder) addStart() {
	b.seq = 1
	b.nodes = append(b.nodes, diagramNode{
		ID:       "1",
		Type:     "start",
		Position: map[string]int{"x": 0, "y": 0},
		Data:     map[string]any{"label": "Start"},
	})
}

// addNode creates a top-level node and returns its id. depth only seeds the placeholder coordinates (a sub-chain starts one
// column to the right); the final coordinates come from layoutDiagram.
func (b *diagramBuilder) addNode(typ, label string, cfg map[string]any, depth int) string {
	return b.addNodeIn(typ, label, cfg, depth, "")
}

// addNodeIn creates a node: with a non-empty parentID it becomes a container child, with coordinates relative to the parent
// and carrying an extent.
//
// The coordinates given here are placeholders only (so that the JSON has a position field); the real layout is computed
// centrally in layoutDiagram - the build phase does not know the shape of the whole graph and cannot produce good
// coordinates.
func (b *diagramBuilder) addNodeIn(typ, label string, cfg map[string]any, depth int, parentID string) string {
	b.seq++
	id := strconv.Itoa(b.seq)
	data := map[string]any{"label": label}
	if len(cfg) > 0 {
		data["config"] = cfg
	}
	n := diagramNode{ID: id, Type: typ, Data: data}
	if parentID == "" {
		n.Position = map[string]int{"x": depth * 280, "y": (b.seq - 1) * 140}
	} else {
		n.Position = map[string]int{"x": 60, "y": 40 + b.childCount(parentID)*140}
		n.ParentNode = parentID
		n.Extent = childExtent()
	}
	b.nodes = append(b.nodes, n)
	return id
}

// childCount is how many children the container already has (it decides where a new child lands vertically).
func (b *diagramBuilder) childCount(parentID string) int {
	n := 0
	for i := range b.nodes {
		if b.nodes[i].ParentNode == parentID {
			n++
		}
	}
	return n
}

// addEdge connects one edge, with a placeholder handle for now.
//
// The real handle is backfilled by fillEdgeHandles once layout is done, from the two nodes' final coordinates - during the
// build the coordinates are still placeholders, and computing the endpoint from them yields values that do not match the
// canvas. A non-empty handle means this is the first edge of a branch sub-chain: its source_handle is a semantic key and
// stays untouched when backfilling.
func (b *diagramBuilder) addEdge(from, to, handle string) {
	if from == "" || to == "" {
		return
	}
	e := diagramEdge{ID: fmt.Sprintf("e%d", len(b.edges)+1), Source: from, Target: to}
	h := "source" + from + "right"
	if handle != "" {
		h = handle
		e.keepSourceHandle = true
	}
	e.SourceHandle = &h
	th := "target" + to + "left"
	e.TargetHandle = &th
	b.edges = append(b.edges, e)
}

// fillEdgeHandles completes / corrects every edge's handles from the final coordinates once layout is done.
//
// Previously only branch sub-chains got a source_handle and main-chain edges were stored as null - harmless at run time (the
// main chain only walks OutEdges[0]), but insert_node refuses them, update_edge has to fill them in first, and a model seeing
// "half of them have a handle, half do not" gets confused. The rule here is uniform: apart from a branch sub-chain's semantic
// key, everything is computed from position.
func (b *diagramBuilder) fillEdgeHandles() {
	for i := range b.edges {
		e := &b.edges[i]
		si, di := b.nodeIndex(e.Source), b.nodeIndex(e.Target)
		if si < 0 || di < 0 {
			continue
		}
		s, d := b.nodes[si], b.nodes[di]
		srcPos, dstPos, _ := suggestHandlePositions(
			s.Type, s.Position["x"], s.Position["y"],
			d.Type, d.Position["x"], d.Position["y"])
		if !e.keepSourceHandle {
			h := "source" + e.Source + srcPos
			e.SourceHandle = &h
		}
		th := "target" + e.Target + dstPos
		e.TargetHandle = &th
	}
}

// nodeIndex finds a node's index by id (shared by the edge backfill and type checks).
func (b *diagramBuilder) nodeIndex(id string) int {
	for i := range b.nodes {
		if b.nodes[i].ID == id {
			return i
		}
	}
	return -1
}

// nodeType finds the type of an already-built node by id.
func (b *diagramBuilder) nodeType(id string) string {
	if i := b.nodeIndex(id); i >= 0 {
		return b.nodes[i].Type
	}
	return ""
}

// emitChain wires one step chain into nodes and edges and returns the chain's tail node id (an empty chain returns from).
//
// A non-empty handle means this chain hangs off one of the branch node's outlets (source<childID>right), in which case the first
// node is reachable only through that edge.
// A non-empty parentID means the chain lives inside a container (loop / process / function) and the nodes all carry
// parent_node.
func (b *diagramBuilder) emitChain(steps []FlowStep, from, handle string, depth int, parentID string) (string, error) {
	prev, prevHandle := from, handle
	for i, st := range steps {
		typ := strings.ToLower(strings.TrimSpace(st.Type))
		if !flowStepTypes[typ] {
			return "", fmt.Errorf("unsupported step type %q. "+
				"Available: llm / code / http / mcp / rpc / branch / intent / loop / process / function / call / "+
				"assign / memory / wait / fork / result / progress / break / continue / return / exit / layout; "+
				"start is generated by the tool, entry is generated by the front end, knowledge has no executor and cannot be created, "+
				"comment can only be created with create_node (pure annotation, no wiring), layout can be created and the runner skips it (pass-through)", st.Type)
		}
		if len(st.Branches) > 0 {
			switch typ {
			case "branch", "intent":
			default:
				return "", fmt.Errorf("step %d (%s) does not support branches: only branch / intent have sub-branches", i+1, typ)
			}
			if i != len(steps)-1 {
				return "", fmt.Errorf("step %d (%s) declares branches and must be the last step of its chain: "+
					"put the steps after the branch into branches[].steps (a branch only takes its default edge once it runs)", i+1, typ)
			}
		}
		// Config shape check: a wrong type is refused outright, a missing required key only produces a warning
		// (the tool allows starting with a minimal config and filling it in on the canvas, consistent with what warnings are
		// for).
		cfgWarnings, cfgErr := validateStepConfig(typ, st.Config)
		if cfgErr != nil {
			return "", cfgErr
		}
		b.warnings = append(b.warnings, cfgWarnings...)

		// Concurrency is off by default: this node's concurrency is handled per the declared policy, and with none declared (off)
		// it is stripped and echoed back; containers never carry the key whatever the policy.
		if w := applyConcurrencyPolicy(st.Config, typ, b.concurrency, fmt.Sprintf("step %d", i+1)); w != "" {
			b.warnings = append(b.warnings, w)
		}

		label := strings.TrimSpace(st.Label)
		if label == "" {
			label = b.uniqueLabel(typ)
		} else if owner := b.labelOwner(label); owner != "" {
			return "", fmt.Errorf(
				"step %d's label %q collides with node %s: node labels must be unique across the flow "+
					"(source_ref / call.target / fork_node_id can all be written as labels, and a duplicate points at the wrong node)",
				i+1, label, owner)
		}
		id := b.addNodeIn(typ, label, st.Config, depth, parentID)
		if st.Position != nil && parentID == "" {
			if b.explicit == nil {
				b.explicit = make(map[string]map[string]int)
			}
			b.explicit[id] = st.Position
		}
		b.addEdge(prev, id, prevHandle)
		prev, prevHandle = id, ""

		if len(st.Children) > 0 {
			switch typ {
			case "loop", "process", "function":
			default:
				return "", fmt.Errorf("step %d (%s) does not support children: only loop / process / function can hold child nodes", i+1, typ)
			}
			if err := b.emitContainerChildren(id, st.Children, depth); err != nil {
				return "", err
			}
		}
		if len(st.Branches) > 0 {
			b.hasBranches = true
			if err := b.emitBranchChains(typ, id, st, depth, parentID); err != nil {
				return "", err
			}
			return id, nil
		}
		// The container already came with a sub-chain, so do not also report "no children - it spins empty at run time"
		if len(st.Children) == 0 {
			if hint := flowStepHint(typ, id, i); hint != "" {
				b.warnings = append(b.warnings, hint)
			}
		}
	}
	return prev, nil
}

// emitContainerChildren creates the entry plus the child chain inside a container.
//
// The executor starts from the entry node whose parent_node is the container id (executors.findEntryNode); without it the
// container "succeeds while running nothing" - so the tool must add the entry, not rely on the caller remembering.
func (b *diagramBuilder) emitContainerChildren(containerID string, children []FlowStep, depth int) error {
	entryID := b.addNodeIn("entry", b.uniqueLabel("Entry"), nil, depth+1, containerID)
	if _, err := b.emitChain(children, entryID, "", depth+1, containerID); err != nil {
		return err
	}
	// Container sub-chains also break linearity (step k is no longer k+1), so the call hint has to be adjusted accordingly.
	b.hasBranches = true
	return nil
}

// emitBranchChains pulls each sub-chain off the branch node per Branches.
//
// The handle convention matches the executor (executors.findBranchEdge does a prefix match):
//
//	ordinary sub-branch: source<childID>right - childID = config.children[].id
//	default branch     : source<node id>right  - the executor finds the default edge by the node's own id
//
// The default branch may be omitted: when the executor finds no default edge it only logs a line, and no condition matching at
// all still counts as a normal finish.
func (b *diagramBuilder) emitBranchChains(typ, nodeID string, st FlowStep, depth int, parentID string) error {
	valid := make(map[string]bool, len(st.Branches)+1)
	valid["default"] = true
	childIDs := make([]string, 0)
	if children, ok := st.Config["children"].([]any); ok {
		for _, c := range children {
			id, _ := objectOf(c)["id"].(string)
			if id = strings.TrimSpace(id); id != "" {
				valid[id] = true
				childIDs = append(childIDs, id)
			}
		}
	}

	declared := make(map[string]bool, len(st.Branches))
	for _, br := range st.Branches {
		key := strings.TrimSpace(br.Key)
		if !valid[key] {
			return fmt.Errorf("branches on %s (id=%s): key=%q is neither an id from config.children nor default; available: %s",
				typ, nodeID, br.Key, strings.Join(append(childIDs, "default"), " / "))
		}
		declared[key] = true
		handle := "source" + key + "right"
		if key == "default" {
			handle = "source" + nodeID + "right"
		}
		if _, err := b.emitChain(br.Steps, nodeID, handle, depth+1, parentID); err != nil {
			return err
		}
	}

	// branches were declared but a sub-branch was left out: once its condition matches there is nowhere to go (the executor only
	// logs "no outgoing edge, skipped").
	// Hint only, never block - building the structure first and adding sub-chains later is allowed.
	for _, id := range childIDs {
		if !declared[id] {
			b.warnings = append(b.warnings, fmt.Sprintf(
				"branch (id=%s): sub-branch %q has no outgoing edge, so it is skipped once its condition is met; "+
					"either add steps under branches or remove it from config.children", nodeID, id))
		}
	}
	return nil
}

// ---------- Layout ----------
//
// The build only handles structure and ids; coordinates are computed centrally in layoutDiagram:
//
//	the main chain runs left to right (nodes on one row share a y), and when a row is full it wraps at the end - no single
//	vertical line stretching hundreds of pixels;
//	each branch of branch / intent gets its own row below the branch node (right -> top into the sub-chain);
//	at a wrap point and at a branch's first node the incoming edge switches to top, so the line follows the height instead of
//	crossing nodes;
//	container children (loop / process / function) are stacked vertically, and the container is sized to its content and the
//	size written into config.size.
//
// Sizes can only be estimated (the backend has no rendering information), using values measured on the frontend: leaves 32
// high, branch / container 300 wide, and label width estimated at 13px per character. Better to leave a little slack than to
// overlap.
const (
	layoutRowMaxWidth = 1500 // how wide one row may get before it wraps
	layoutColGap      = 80   // horizontal gap between adjacent nodes on a row
	layoutRowGap      = 120  // vertical gap after a wrap (the height a row's branches take is counted separately)
	layoutBranchGap   = 60   // distance from the branch node's bottom to its first branch node
	layoutBranchStep  = 40   // extra gap between two branches of the same branch node
	layoutOrphanGap   = 120  // gap below the graph for orphan nodes (no incoming edge, unreachable from start)
	// Leading margin: the canvas viewport is pinned at (0,0) and nodes hugging the top-left corner look cramped; this matches
	// the frontend "new flow" default of putting start at (100,50)
	layoutMarginX = 100
	layoutMarginY = 50

	// Container layout: coordinates are relative to the parent, aligned with the frontend nodeFactory's 37px top margin
	childBaseX = 20
	childBaseY = 37
	childGap   = 24
)

// nodeSize estimates a node's size on the canvas (width, height).
func nodeSize(n diagramNode) (int, int) {
	label, _ := n.Data["label"].(string)
	cfg, _ := n.Data["config"].(map[string]any)
	switch n.Type {
	case "start":
		return 120, 40
	case "branch", "intent":
		rows := 1
		if children, ok := cfg["children"].([]any); ok && len(children) > 0 {
			rows = len(children)
		}
		return 300, 44 + 28*rows
	case "loop", "process", "function":
		return 300, 100
	case "layout":
		// A 32px dot whose name shows on hover; it barely takes up space
		return 60, 32
	}
	w := 56 + 13*len([]rune(label))
	if w < 120 {
		w = 120
	}
	if w > 280 {
		w = 280
	}
	h := 32
	// A node with concurrency on (config.concurrency = {mode, fork_node_id}) gains an extra row of "concurrency control +
	// dropdown + cancel": its width reaches 280 and its height roughly doubles.
	// Missing this block makes the layout overlap its neighbours and the overlap check misjudge.
	if hasConcurrency(cfg) {
		if w < 280 {
			w = 280
		}
		h = 64
	}
	return w, h
}

// hasConcurrency reports whether a node has concurrency on (config.concurrency is non-empty).
func hasConcurrency(cfg map[string]any) bool {
	c, ok := cfg["concurrency"].(map[string]any)
	return ok && len(c) > 0
}

// diagramLayout is the layout context: the graph's adjacency, the placed set and the final sizes.
type diagramLayout struct {
	b     *diagramBuilder
	byID  map[string]int
	out   map[string][]int // edge indexes by source node id
	topTo map[string]bool  // nodes whose incoming edge enters via top (a wrap head / a branch head)
	sizes map[string][2]int
	taken map[string]bool
}

// newDiagramLayout builds the layout context (the adjacency maps to edge indexes, so a target_handle can be rewritten
// directly).
func newDiagramLayout(b *diagramBuilder) *diagramLayout {
	l := &diagramLayout{
		b:     b,
		byID:  make(map[string]int, len(b.nodes)),
		out:   make(map[string][]int, len(b.edges)),
		topTo: make(map[string]bool, len(b.nodes)),
		sizes: make(map[string][2]int, len(b.nodes)),
		taken: make(map[string]bool, len(b.nodes)),
	}
	for i := range b.nodes {
		l.byID[b.nodes[i].ID] = i
	}
	for i := range b.edges {
		l.out[b.edges[i].Source] = append(l.out[b.edges[i].Source], i)
	}
	return l
}

// applyModelPositions lays out using the coordinates the model gave; true means everything was placed as given.
//
// It only accepts "all top-level nodes given": mixing in code-computed coordinates makes them overlap, and the model could not
// tell which part it laid out itself. If one is missing the whole graph falls back to automatic layout and the warnings name
// the missing ones - so the model fills them in next round instead of guessing.
func (b *diagramBuilder) applyModelPositions() bool {
	if len(b.explicit) == 0 {
		return false
	}
	missing := make([]string, 0, 2)
	for i := range b.nodes {
		n := &b.nodes[i]
		if n.ParentNode != "" || n.ID == "1" {
			continue
		}
		if _, ok := b.explicit[n.ID]; !ok {
			missing = append(missing, n.ID)
		}
	}
	if len(missing) > 0 {
		b.warnings = append(b.warnings, fmt.Sprintf(
			"%d top-level nodes have no position (%s): coordinates must be given for all of them or none — "+
				"a partial set mixed with auto layout overlaps itself, so auto layout is used this time", len(missing), strings.Join(missing, ", ")))
		return false
	}

	for i := range b.nodes {
		if pos, ok := b.explicit[b.nodes[i].ID]; ok {
			b.nodes[i].Position = pos
		}
	}
	// start is generated by the tool and the model cannot give it coordinates: place it 200px to the left of the first node, on
	// the same row
	if first := b.firstPositionedNode(); first != "" {
		p := b.explicit[first]
		x := p["x"] - 200
		if x < 0 {
			x = 0
		}
		b.setNodePosition("1", map[string]int{"x": x, "y": p["y"]})
	}
	// The inside of containers is still laid out by the tool (relative coordinates) with config.size written
	b.layoutContainersOnly()
	b.warnOverlaps()
	return true
}

// firstPositionedNode finds, in build order, the first top-level node with coordinates (start excluded).
func (b *diagramBuilder) firstPositionedNode() string {
	for i := range b.nodes {
		n := &b.nodes[i]
		if n.ParentNode != "" || n.ID == "1" {
			continue
		}
		if _, ok := b.explicit[n.ID]; ok {
			return n.ID
		}
	}
	return ""
}

// setNodePosition changes an existing node's coordinates (silently ignored when not found).
func (b *diagramBuilder) setNodePosition(id string, pos map[string]int) {
	for i := range b.nodes {
		if b.nodes[i].ID == id {
			b.nodes[i].Position = pos
			return
		}
	}
}

// warnOverlaps checks whether top-level nodes overlap: it warns but never moves them -
// the coordinates are the model's, and moving them would break its own composition; let it decide how to yield.
func (b *diagramBuilder) warnOverlaps() {
	l := newDiagramLayout(b)
	type box struct {
		id   string
		x, y int
		w, h int
	}
	boxes := make([]box, 0, len(b.nodes))
	for i := range l.b.nodes {
		n := &l.b.nodes[i]
		if n.ParentNode != "" {
			continue
		}
		w, h := l.sizeOf(n.ID)
		boxes = append(boxes, box{n.ID, n.Position["x"], n.Position["y"], w, h})
	}
	for i := 0; i < len(boxes); i++ {
		for j := i + 1; j < len(boxes); j++ {
			a, c := boxes[i], boxes[j]
			if a.x < c.x+c.w && c.x < a.x+a.w && a.y < c.y+c.h && c.y < a.y+a.h {
				b.warnings = append(b.warnings, fmt.Sprintf(
					"nodes %s and %s overlap: move one with update_node's position (x gap ≥ 80, y gap ≥ 40 suggested)",
					a.id, c.id))
			}
		}
	}
}

// layoutContainersOnly lays out only the inside of containers (used when the model supplied the top-level coordinates):
// children are stacked vertically and the container is sized to its bounding box, written into config.size.
func (b *diagramBuilder) layoutContainersOnly() {
	l := newDiagramLayout(b)
	for i := range b.nodes {
		n := &b.nodes[i]
		if n.ParentNode == "" && containerTypes[n.Type] {
			l.containerChildren(n.ID)
		}
	}
}

// layoutDiagram lays out the whole graph and rewrites the incoming edges that need to enter via top.
func (b *diagramBuilder) layoutDiagram() {
	l := newDiagramLayout(b)
	start := "1"
	if _, ok := l.byID[start]; !ok {
		start = l.firstRoot()
	}
	if start != "" {
		l.chain(start, layoutMarginX, layoutMarginY, layoutRowMaxWidth)
	}
	l.placeOrphans()
	for i := range b.edges {
		if !l.topTo[b.edges[i].Target] {
			continue
		}
		h := "target" + b.edges[i].Target + "top"
		b.edges[i].TargetHandle = &h
	}
}

// firstRoot finds a top-level node with no incoming edge (the fallback when start is absent).
func (l *diagramLayout) firstRoot() string {
	in := make(map[string]bool, len(l.b.edges))
	for _, e := range l.b.edges {
		in[e.Target] = true
	}
	for i := range l.b.nodes {
		n := &l.b.nodes[i]
		if n.ParentNode == "" && !in[n.ID] {
			return n.ID
		}
	}
	return ""
}

// sizeOf returns a node's final size; once a container is expanded in containerChildren that overrides the estimate here.
func (l *diagramLayout) sizeOf(id string) (int, int) {
	if s, ok := l.sizes[id]; ok {
		return s[0], s[1]
	}
	idx, ok := l.byID[id]
	if !ok {
		return 120, 32
	}
	w, h := nodeSize(l.b.nodes[idx])
	l.sizes[id] = [2]int{w, h}
	return w, h
}

// next returns the sole successor (0 or several outgoing edges both mean "no linear successor").
func (l *diagramLayout) next(id string) string {
	out := l.out[id]
	if len(out) != 1 {
		return ""
	}
	return l.b.edges[out[0]].Target
}

// chain places one chain starting at startID on the canvas and returns that chain's right and bottom bounds.
// x/y is where the chain starts; limit is the row width cap (after a wrap it returns to the column at x).
func (l *diagramLayout) chain(startID string, x, y, limit int) (int, int) {
	cur := startID
	baseX := x
	rowY := y
	branchBottom := y // the lowest point this row's branches occupy, to keep clear of when wrapping
	right, bottom := x, y

	for cur != "" {
		idx, ok := l.byID[cur]
		if !ok || l.taken[cur] {
			break
		}
		w, h := l.sizeOf(cur)
		// Wrap: when the row is full, start a new one and clear the height this row's branches occupy
		if cur != startID && x > baseX && x+w > limit {
			rowY = branchBottom + layoutRowGap
			branchBottom = rowY
			x = baseX
			l.topTo[cur] = true
		}

		node := &l.b.nodes[idx]
		node.Position = map[string]int{"x": x, "y": rowY}
		l.taken[cur] = true

		if containerTypes[node.Type] {
			l.containerChildren(cur)
			w, h = l.sizeOf(cur)
		}
		if x+w > right {
			right = x + w
		}
		if rowY+h > bottom {
			bottom = rowY + h
		}

		// Branch node: each branch gets its own row below and the main chain ends here (the same rule as emitChain's build)
		if node.Type == "branch" || node.Type == "intent" {
			cursor := rowY + h + layoutBranchGap
			for _, ei := range l.out[cur] {
				target := l.b.edges[ei].Target
				if l.taken[target] {
					continue
				}
				// The first node sits below-right of the branch node: its right outlet feeds the node's top
				l.topTo[target] = true
				_, bBottom := l.chain(target, x+layoutBranchStep, cursor, limit)
				if bBottom > bottom {
					bottom = bBottom
				}
				cursor = bBottom + layoutBranchStep
			}
			if cursor-layoutBranchStep > branchBottom {
				branchBottom = cursor - layoutBranchStep
			}
			return right, bottom
		}

		next := l.next(cur)
		if next == "" {
			break
		}
		x += w + layoutColGap
		cur = next
	}
	return right, bottom
}

// containerChildren lays out a container's children (relative coordinates) and expands the container to its bounding box.
func (l *diagramLayout) containerChildren(containerID string) {
	children := make([]string, 0, 4)
	for i := range l.b.nodes {
		if l.b.nodes[i].ParentNode == containerID {
			children = append(children, l.b.nodes[i].ID)
		}
	}
	if len(children) == 0 {
		return
	}

	x := childBaseX
	y := childBaseY
	maxW, maxH := 300, 100
	for _, cid := range children {
		idx := l.byID[cid]
		child := &l.b.nodes[idx]
		if containerTypes[child.Type] {
			l.containerChildren(cid)
		}
		w, h := l.sizeOf(cid)
		child.Position = map[string]int{"x": x, "y": y}
		l.taken[cid] = true
		if right := x + w + childBaseX; right > maxW {
			maxW = right
		}
		y += h + childGap
		if bottom := y - childGap + childBaseX; bottom > maxH {
			maxH = bottom
		}
	}

	// Write config.size back: the frontend LoopNode/ProcessNode/FunctionNode read it directly for width and height; without it
	// the canvas renders at the default 300x100 first and only expands on the next frame, which looks like a jitter.
	node := &l.b.nodes[l.byID[containerID]]
	cfg, _ := node.Data["config"].(map[string]any)
	if cfg == nil {
		cfg = map[string]any{}
		node.Data["config"] = cfg
	}
	cfg["size"] = map[string]any{
		"width":  fmt.Sprintf("%dpx", maxW),
		"height": fmt.Sprintf("%dpx", maxH),
	}
	l.sizes[containerID] = [2]int{maxW, maxH}
}

// placeOrphans appends top-level nodes unreachable from start to the bottom of the graph so they do not all pile up at (0,0).
func (l *diagramLayout) placeOrphans() {
	maxBottom := 0
	for i := range l.b.nodes {
		n := &l.b.nodes[i]
		if n.ParentNode != "" || !l.taken[n.ID] {
			continue
		}
		if _, h := l.sizeOf(n.ID); n.Position["y"]+h > maxBottom {
			maxBottom = n.Position["y"] + h
		}
	}
	y := maxBottom + layoutOrphanGap
	for i := range l.b.nodes {
		n := &l.b.nodes[i]
		if n.ParentNode != "" || l.taken[n.ID] {
			continue
		}
		_, h := l.sizeOf(n.ID)
		n.Position = map[string]int{"x": 0, "y": y}
		l.taken[n.ID] = true
		y += h + layoutRowGap
	}
}

// labelOwner returns the id of the node already using that label ("" = unused).
//
// label is the writable form of source_ref / call.target / fork_node_id, and a duplicate makes those references point at the
// wrong node, so every node's label must be unique while the graph is built.
func (b *diagramBuilder) labelOwner(label string) string {
	label = strings.TrimSpace(label)
	if label == "" {
		return ""
	}
	for _, n := range b.nodes {
		if l, _ := n.Data["label"].(string); strings.TrimSpace(l) == label {
			return n.ID
		}
	}
	return ""
}

// uniqueLabel appends -2 / -3 ... to an **auto-generated** label until it is unique in the graph;
// a collision on a label the user wrote explicitly is an error in emitChain, never a silent rename.
func (b *diagramBuilder) uniqueLabel(base string) string {
	base = strings.TrimSpace(base)
	if base == "" {
		base = "Node"
	}
	if b.labelOwner(base) == "" {
		return base
	}
	for i := 2; i <= 999; i++ {
		if candidate := fmt.Sprintf("%s-%d", base, i); b.labelOwner(candidate) == "" {
			return candidate
		}
	}
	return fmt.Sprintf("%s-%d", base, len(b.nodes)+1)
}

// resolveSourceRefs replaces values in config.inputs / config.targets / config.args source_ref that were written as a node
// label with the node id.
//
// The model is bad at computing ids by hand (branch sub-chains are spliced in, so step k is no longer k+1), while a label it just
// wrote is something it does remember. A value is only replaced by label when it matches no node id: id first, so that a label
// which happens to be a digit string cannot corrupt a correct id.
//
// The three sections all carry the same field shape, and all three are read as "the variable comes from that node", so they are
// rewritten together: leaving targets or args out made a label pass creation and fail at run time.
func (b *diagramBuilder) resolveSourceRefs() {
	byLabel := make(map[string]string, len(b.nodes))
	ids := make(map[string]bool, len(b.nodes))
	for _, n := range b.nodes {
		ids[n.ID] = true
		label, _ := n.Data["label"].(string)
		if _, dup := byLabel[label]; label == "" || dup {
			continue // a duplicated label is not used for rewriting: when ambiguous, leave it as is rather than guess
		}
		byLabel[label] = n.ID
	}
	for _, n := range b.nodes {
		cfg := objectOf(n.Data["config"])
		for _, section := range []string{"inputs", "targets", "args"} {
			vars, _ := cfg[section].(map[string]any)
			for _, v := range vars {
				def, ok := v.(map[string]any)
				if !ok {
					continue
				}
				ref, _ := def["source_ref"].(string)
				if ref == "" || ids[ref] {
					continue
				}
				if id, ok := byLabel[ref]; ok {
					def["source_ref"] = id
				}
			}
		}
	}
}

// warnCalls: call's target must be the id of a function node in the same flow.
// In a purely linear graph step k has id k+1, which can be said outright; once branches / container sub-chains exist the ids are
// no longer linear, so the caller has to read the real ids back - guessing wrong is a run-time config error, which costs more
// than one extra read_flow.
func (b *diagramBuilder) warnCalls() {
	for _, n := range b.nodes {
		if n.Type != "call" {
			continue
		}
		if b.hasBranches {
			b.warnings = append(b.warnings, fmt.Sprintf(
				"call (id=%s): target must point at a function node in this flow; this diagram contains branches / container sub-chains, so node ids cannot be derived from the step index — "+
					"call read_flow first to get the real ids", n.ID))
			continue
		}
		b.warnings = append(b.warnings, fmt.Sprintf(
			"call (id=%s): target must be the id of a function node in the same flow (the node id of step k is k+1)", n.ID))
	}
}

// validateStepConfig validates the shape of a step's config.
//
// The rules live in shared/flowcheck so that the create tools, the save boundary and the validate_flow tool share one
// implementation: a second opinion is how "the check passed but the run failed" becomes normal.
//
// The split: a wrong shape (a block that is not an object, children that are not an array, an illegal loop.type) cannot be
// rescued on the canvas either, so it is refused outright; a missing required key only produces a warning - starting from a
// minimal config and filling structural gaps in on the canvas is allowed (the same stance as flowStepHint).
func validateStepConfig(typ string, cfg map[string]any) ([]string, error) {
	findings, err := flowcheck.Step(typ, cfg, sandboxScriptLangs())
	if err != nil {
		return nil, err
	}
	warnings := make([]string, 0, len(findings))
	for _, f := range findings {
		warnings = append(warnings, f.Message)
	}
	return warnings, nil
}

// sandboxScriptLangs returns the sandbox's workflow script language list, or nil when the sandbox is down / too old to
// report it. nil means "unknown": the language check is skipped rather than guessed.
func sandboxScriptLangs() []string {
	if langs, ok := sandboxinfo.CodeLangs(); ok {
		return langs
	}
	return nil
}

// objectOf takes a map[string]any; anything else counts as "absent", and shape errors are caught earlier by
// validateStepConfig.
func objectOf(v any) map[string]any {
	m, _ := v.(map[string]any)
	return m
}

// parseFlowSteps parses the steps argument: each entry is {type, label?, config?, branches?}.
func parseFlowSteps(raw any) ([]FlowStep, error) { return parseStepList(raw, "steps") }

// parseStepList parses one step chain recursively; path is only used to locate errors (steps / steps[1].branches[0].steps).
func parseStepList(raw any, path string) ([]FlowStep, error) {
	list, ok := raw.([]any)
	if !ok || len(list) == 0 {
		if path == "steps" {
			return nil, errors.New("steps must be a non-empty array")
		}
		return nil, fmt.Errorf("%s must be a non-empty array", path)
	}
	steps := make([]FlowStep, 0, len(list))
	for i, it := range list {
		m, ok := it.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("%s[%d] is not an object", path, i)
		}
		st := FlowStep{
			Type:  argString(m, "type"),
			Label: argString(m, "label"),
		}
		if cfg, ok := m["config"].(map[string]any); ok {
			st.Config = cfg
		} else if m["config"] != nil {
			return nil, fmt.Errorf("%s[%d].config must be an object", path, i)
		}
		if strings.TrimSpace(st.Type) == "" {
			return nil, fmt.Errorf("%s[%d].type must not be empty", path, i)
		}
		if rawPos, exists := m["position"]; exists && rawPos != nil {
			pos, err := parseStepPosition(rawPos, fmt.Sprintf("%s[%d].position", path, i))
			if err != nil {
				return nil, err
			}
			st.Position = pos
		}
		if rawBranches, exists := m["branches"]; exists {
			branches, err := parseFlowBranches(rawBranches, fmt.Sprintf("%s[%d].branches", path, i))
			if err != nil {
				return nil, err
			}
			st.Branches = branches
		}
		if rawChildren, exists := m["children"]; exists && rawChildren != nil {
			children, err := parseStepList(rawChildren, fmt.Sprintf("%s[%d].children", path, i))
			if err != nil {
				return nil, err
			}
			st.Children = children
		}
		steps = append(steps, st)
	}
	return steps, nil
}

// parseStepPosition parses position on a step: {x, y} (px in canvas coordinates).
func parseStepPosition(raw any, path string) (map[string]int, error) {
	m, ok := raw.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%s must be an {x, y} object", path)
	}
	x, okX := positionAxis(m["x"])
	y, okY := positionAxis(m["y"])
	if !okX || !okY {
		return nil, fmt.Errorf("%s: x / y must be numbers (px, canvas coordinates)", path)
	}
	return map[string]int{"x": x, "y": y}, nil
}

// positionAxis converts a JSON number to int; it accepts float64 / int / json.Number.
func positionAxis(v any) (int, bool) {
	switch n := v.(type) {
	case float64:
		return int(n), true
	case int:
		return n, true
	case int64:
		return int(n), true
	case json.Number:
		i, err := n.Int64()
		if err != nil {
			return 0, false
		}
		return int(i), true
	}
	return 0, false
}

// parseFlowBranches parses branches: [{key, steps}].
//
// An array rather than an object: node ids are allocated in declaration order, and a JSON object decodes in no fixed order in
// Go - the same input would build different ids and edges, and both read_flow and later references would drift.
func parseFlowBranches(raw any, path string) ([]FlowBranch, error) {
	list, ok := raw.([]any)
	if !ok || len(list) == 0 {
		return nil, fmt.Errorf("%s must be a non-empty array of {key, steps}", path)
	}
	branches := make([]FlowBranch, 0, len(list))
	seen := make(map[string]bool, len(list))
	for i, it := range list {
		m, ok := it.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("%s[%d] is not an object", path, i)
		}
		key := strings.TrimSpace(argString(m, "key"))
		if key == "" {
			return nil, fmt.Errorf("%s[%d].key must not be empty: use a config.children[].id or default", path, i)
		}
		if seen[key] {
			return nil, fmt.Errorf("%s declares branch %q twice (each sub-branch takes exactly one chain)", path, key)
		}
		seen[key] = true
		steps, err := parseStepList(m["steps"], fmt.Sprintf("%s[%d].steps", path, i))
		if err != nil {
			return nil, err
		}
		branches = append(branches, FlowBranch{Key: key, Steps: steps})
	}
	return branches, nil
}

// parseFlowEndpoints parses external_protocols:
// only mcp / rpc are accepted, de-duplicated while keeping the given order.
//
// The svc_endpoints table also allows llm, but that is for "direct model access", not a service entry for a workflow to be
// exposed on; letting a protocol with no consumer through here would only make the exposed protocols look more usable than they
// are.
// An unrecognisable shape (not a string array) counts as "not passed" - the same convention as argStringSlice.
func parseFlowEndpoints(args map[string]any) ([]string, error) {
	raw, ok := argStringSlice(args, "external_protocols")
	if !ok {
		return nil, nil
	}
	seen := make(map[string]bool, len(raw))
	out := make([]string, 0, len(raw))
	for _, p := range raw {
		p = strings.ToLower(p)
		switch p {
		case "mcp", "rpc":
		default:
			return nil, fmt.Errorf("external_protocols supports mcp / rpc only, got %q", p)
		}
		if seen[p] {
			continue
		}
		seen[p] = true
		out = append(out, p)
	}
	return out, nil
}

// ===== Entry arguments (flows.arguments) =====
//
// arguments is a "declaration", not run-time input: it is at once the endpoint's external input_schema and what the frontend
// "entry arguments" panel reads, and run_flow's inputs key aligns with it. So it must be validated before it is stored - a
// broken schema does not fail at creation, it only turns into "no description / required has no effect" on the caller's side.

// flowArgTypes are the JSON Schema types entry arguments allow (the same set as the frontend editor and the executor's
// InitArguments).
var flowArgTypes = map[string]bool{
	"string": true, "number": true, "boolean": true, "object": true, "array": true,
}

// flowArgNameRe: a parameter name becomes a variable name in template blocks and a key of input_schema.
// A name containing a dot is split into a nested path by GetVarByPath (a.b is read as b of a), and the frontend concatenates
// nested paths with dots too, so dots / brackets are refused outright.
var flowArgNameRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// parseFlowArguments normalises create_flow's arguments and returns the JSON to store plus the parameter names.
// Both forms are accepted: a full schema (properties / required) and the shorthand that omits the outer shell.
func parseFlowArguments(raw any) (json.RawMessage, []string, error) {
	if raw == nil {
		return nil, nil, nil
	}
	m, ok := raw.(map[string]any)
	if !ok {
		return nil, nil, errors.New(`arguments must be an object, e.g. {"properties":{"city":{"type":"string"}},"required":["city"]}`)
	}

	propsRaw := m
	if v, has := m["properties"]; has {
		pm, ok := v.(map[string]any)
		if !ok {
			return nil, nil, errors.New("arguments.properties must be an object (keys are parameter names)")
		}
		propsRaw = pm
	} else {
		// Shorthand: {"city":{"type":"string"}}; required may be written alongside, outside
		propsRaw = make(map[string]any, len(m))
		for k, v := range m {
			switch k {
			case "required":
			case "type", "description":
				return nil, nil, errors.New(`arguments has type / description but no properties: write {"type":"object","properties":{...}}`)
			default:
				propsRaw[k] = v
			}
		}
	}

	props, err := validateFlowArgProps(propsRaw, "")
	if err != nil {
		return nil, nil, err
	}
	required, err := flowArgRequired(m["required"], props, "")
	if err != nil {
		return nil, nil, err
	}
	if len(props) == 0 && len(required) == 0 {
		return nil, nil, nil // an empty declaration is no declaration; do not store an empty schema
	}

	names := make([]string, 0, len(props))
	for name := range props {
		names = append(names, name)
	}
	sort.Strings(names)

	doc := map[string]any{"type": "object", "properties": props}
	if len(required) > 0 {
		doc["required"] = flowArgAnySlice(required)
	}
	buf, err := json.Marshal(doc)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to serialize arguments: %w", err)
	}
	return json.RawMessage(buf), names, nil
}

// validateFlowArgProps validates properties recursively and keeps only known fields (a misspelled key is caught rather than
// stored).
func validateFlowArgProps(props map[string]any, prefix string) (map[string]any, error) {
	out := make(map[string]any, len(props))
	for name, raw := range props {
		if !flowArgNameRe.MatchString(name) {
			return nil, fmt.Errorf("invalid parameter name %q: letters, digits and underscores only, and it must not start with a digit (it becomes a variable name in template blocks)", prefix+name)
		}
		spec, ok := raw.(map[string]any)
		if !ok {
			return nil, fmt.Errorf(`parameter %q must be an object, e.g. {"type":"string","description":"..."}`, prefix+name)
		}
		typ := strings.TrimSpace(argString(spec, "type"))
		if typ == "" {
			return nil, fmt.Errorf("parameter %q has no type (string / number / boolean / object / array)", prefix+name)
		}
		if !flowArgTypes[typ] {
			return nil, fmt.Errorf("parameter %q has unsupported type=%q: only string / number / boolean / object / array", prefix+name, typ)
		}
		clean := map[string]any{"type": typ}
		for _, k := range []string{"description", "default"} {
			if v, ok := spec[k]; ok {
				clean[k] = v
			}
		}
		switch typ {
		case "object":
			subRaw := map[string]any{}
			if v, ok := spec["properties"]; ok {
				pm, ok := v.(map[string]any)
				if !ok {
					return nil, fmt.Errorf("parameter %q: properties must be an object", prefix+name)
				}
				subRaw = pm
			}
			sub, err := validateFlowArgProps(subRaw, prefix+name+".")
			if err != nil {
				return nil, err
			}
			clean["properties"] = sub
			req, err := flowArgRequired(spec["required"], sub, prefix+name+".")
			if err != nil {
				return nil, err
			}
			if len(req) > 0 {
				clean["required"] = flowArgAnySlice(req)
			}
		case "array":
			items, ok := spec["items"].(map[string]any)
			if !ok {
				return nil, fmt.Errorf(`parameter %q is an array and needs items, e.g. {"type":"array","items":{"type":"string"}}`, prefix+name)
			}
			it := strings.TrimSpace(argString(items, "type"))
			if !flowArgTypes[it] || it == "array" {
				return nil, fmt.Errorf("parameter %q: items.type must be string / number / boolean / object (wrap nested arrays in an object)", prefix+name)
			}
			cleanItems := map[string]any{"type": it}
			if it == "object" {
				subRaw := map[string]any{}
				if v, ok := items["properties"]; ok {
					pm, ok := v.(map[string]any)
					if !ok {
						return nil, fmt.Errorf("parameter %q: items.properties must be an object", prefix+name)
					}
					subRaw = pm
				}
				sub, err := validateFlowArgProps(subRaw, prefix+name+"[].")
				if err != nil {
					return nil, err
				}
				cleanItems["properties"] = sub
				req, err := flowArgRequired(items["required"], sub, prefix+name+"[].")
				if err != nil {
					return nil, err
				}
				if len(req) > 0 {
					cleanItems["required"] = flowArgAnySlice(req)
				}
			}
			clean["items"] = cleanItems
		}
		out[name] = clean
	}
	return out, nil
}

// flowArgRequired validates that required only lists names present in properties (a misspelled name is a "required that never
// takes effect").
func flowArgRequired(raw any, props map[string]any, prefix string) ([]string, error) {
	if raw == nil {
		return nil, nil
	}
	where := "arguments"
	if prefix != "" {
		where = "parameter " + strings.TrimSuffix(prefix, ".")
	}
	list, ok := raw.([]any)
	if !ok {
		return nil, fmt.Errorf("%s: required must be an array of strings", where)
	}
	seen := make(map[string]bool, len(list))
	out := make([]string, 0, len(list))
	for _, item := range list {
		name, ok := item.(string)
		if !ok || name == "" {
			return nil, fmt.Errorf("%s: one required entry is not a parameter name: %v", where, item)
		}
		if _, exists := props[name]; !exists {
			return nil, fmt.Errorf("%s: required lists %q but properties has no such parameter", where, name)
		}
		if seen[name] {
			continue
		}
		seen[name] = true
		out = append(out, name)
	}
	return out, nil
}

// flowArgAnySlice converts []string to []any so that it encodes as a JSON array rather than a Go type string.
func flowArgAnySlice(in []string) []any {
	out := make([]any, len(in))
	for i, s := range in {
		out[i] = s
	}
	return out
}

