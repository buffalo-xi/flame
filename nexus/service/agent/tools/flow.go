func (t *runFlowTool) Execute(ctx context.Context, c *Context, args map[string]any) (any, error) {
	if c.Flows == nil {
		return nil, errors.New("flow manager not available")
	}
	ref := strings.TrimSpace(argString(args, "flow"))
	if ref == "" {
		return nil, errors.New("a workflow id or name is required")
	}
	inputs, err := argObject(args, "inputs")
	if err != nil {
		return nil, err
	}
	// Session and stack depth are passed down together: if the flow has agent nodes, they share this run's venue and depth chain.
	// Only a valid UUID is passed: NewFlow errors out on a bad session_id, and "session_id is not a valid UUID" reads as "the flow
	// will not run" rather than the real cause (the caller's session id is malformed) - falling back to a temporary venue is
	// enough.
	sessionID := c.SessionID
	if _, perr := uuid.Parse(sessionID); perr != nil {
		sessionID = ""
	}
	// Sub-flow version: by default it follows this run's "sub-calls follow drafts" switch (on by default in chat, the same
	// meaning as the editor debugger's).
	// An explicit false tightens it to released versions; an explicit true has no effect in a formal run - drafts never spread
	// out of the production chain.
	followDrafts := c.ChildMode() == ModeDraft
	if raw, ok := args["follow_drafts"]; ok && raw != nil {
		followDrafts = followDrafts && argBool(args, "follow_drafts")
	}
	// The ancestor chain reaches the execution layer through ctx (run_flow's test run uses the same rule as an rpc node, rather
	// than adding a parameter to the signature)
	ctx = callchain.With(ctx, c.CallChain)
	res, err := c.Flows.RunTest(ctx, ref, inputs, sessionID, c.CallDepth, followDrafts)
	if err != nil {
		return nil, err
	}
	if res == nil {
		return nil, fmt.Errorf("workflow %q does not exist", ref)
	}
	clipFlowRun(res, c.MaxOutputLimit())
	return res, nil
}

// flowRunNodeLogLimit is the return cap (in bytes) for one node's logs / error stack. A script's stderr can be long, but
// locating the problem only needs the tail: the traceback and the real error are at the end.
const flowRunNodeLogLimit = 2000

// clipFlowRun clips to the caller's output limit: the final output gets the full allowance, and each failed node's logs and stack
// are capped individually.
// Only the copy returned to the model is clipped - the run record stores the complete data.
func clipFlowRun(res *FlowRunResult, limit int) {
	if limit <= 0 {
		limit = DefaultMaxOutput
	}
	if clipped := cutHeadBytes(res.Result, limit); clipped != res.Result {
		res.Result = clipped
		res.Truncated = true
	}
	for i := range res.Nodes {
		if clipped := cutTailBytes(res.Nodes[i].Logs, flowRunNodeLogLimit); clipped != res.Nodes[i].Logs {
			res.Nodes[i].Logs = clipped
			res.Truncated = true
		}
		if clipped := cutTailBytes(res.Nodes[i].ErrStack, flowRunNodeLogLimit); clipped != res.Nodes[i].ErrStack {
			res.Nodes[i].ErrStack = clipped
			res.Truncated = true
		}
	}
}

