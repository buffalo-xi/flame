// ProxyGateway is the LiteLLM Proxy gateway implementation.
type ProxyGateway struct {
	URL       string
	MasterKey string
	client    *http.Client
	// db connects to LiteLLM's own Postgres database (litellm.database in the yaml), used to query its
	// registry directly.
	// dbMu guards concurrent access to the db pointer (a background reconnect goroutine may be swapping
	// the connection); dbConnected is atomic, so reading it needs no lock.
	db          *sql.DB
	dbConnected atomic.Bool
	dbMu        sync.RWMutex
}

// New creates a LiteLLM Proxy gateway instance.
// db may be nil, which means the LiteLLM database is not connected yet (dbConnected=false); the caller
// then injects the connection through SetDB after OpenDatabase succeeds in its reconnect goroutine
// (so that initialization is not blocked).
func New(url, masterKey string, db *sql.DB) *ProxyGateway {
	g := &ProxyGateway{
		URL:       strings.TrimRight(url, "/"),
		MasterKey: masterKey,
		client:    &http.Client{},
		db:        db,
	}
	if db != nil {
		g.dbConnected.Store(true)
	}
	return g
}

// IsConnected reports the connection state of the LiteLLM database.
func (g *ProxyGateway) IsConnected() bool { return g.dbConnected.Load() }

// SetDB replaces the LiteLLM database connection and marks it connected (the old connection is closed).
// Called by the caller (the reconnect goroutine in main) once OpenDatabase succeeded.
func (g *ProxyGateway) SetDB(db *sql.DB) {
	g.dbMu.Lock()
	defer g.dbMu.Unlock()
	if g.db != nil {
		g.db.Close()
	}
	g.db = db
	g.dbConnected.Store(true)
}

// Ping checks the LiteLLM database connection and mirrors the result into dbConnected:
// nil or a failed Ping sets false, success sets true.
func (g *ProxyGateway) Ping() error {
	g.dbMu.RLock()
	db := g.db
	g.dbMu.RUnlock()

	if db == nil {
		g.dbConnected.Store(false)
		return fmt.Errorf("litellm database not connected")
	}
	if err := db.Ping(); err != nil {
		g.dbConnected.Store(false)
		return err
	}
	g.dbConnected.Store(true)
	return nil
}

// liteLLMModelTable is the table LiteLLM stores registered models in.
// The name is actually mixed case in Postgres (LiteLLM_ProxyModelTable) and must be double quoted;
// otherwise the unquoted identifier is folded to lower case and the relation is not found.
const liteLLMModelTable = `"LiteLLM_ProxyModelTable"`

// queryLiteLLMTable looks a model_id (UUID) up in LiteLLM's own registry to tell whether the model is registered.
func (g *ProxyGateway) queryLiteLLMTable(modelID string) (bool, error) {
	g.dbMu.RLock()
	db := g.db
	g.dbMu.RUnlock()
	if db == nil {
		return false, fmt.Errorf("litellm database connection not initialized")
	}
	var exists bool
	query := fmt.Sprintf("SELECT EXISTS(SELECT 1 FROM %s WHERE model_id = $1)", liteLLMModelTable)
	if err := db.QueryRow(query, modelID).Scan(&exists); err != nil {
		return false, fmt.Errorf("query litellm model table: %w", err)
	}
	return exists, nil
}

