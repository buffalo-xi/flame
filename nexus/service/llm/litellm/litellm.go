// Provision checks whether the model is registered on the gateway and registers it when it is not; it
// returns the gatewayID (the model_id UUID of LiteLLM).
// The authoritative source is model.GatewayID (the UUID stored in the DB), looked up directly in
// LiteLLM's own registry table:
//   - found: it is already registered, return that id;
//   - not found (including an empty GatewayID, i.e. first enable): register again (overwriting the
//     previous gateway_id).
//
// Note: there is no longer a "look up by model_name and reuse", because model_name may be duplicated and
// reusing by name hits the wrong row or misses the right one. The only authoritative key is the
// gatewayID (UUID).
func (g *ProxyGateway) Provision(schema string, model gateway.ModelInput, provider gateway.ProviderInput) (string, error) {
	// Use the gateway_id (UUID) stored in the DB as the authority and query the LiteLLM registry directly.
	if model.GatewayID != "" {
		exists, err := g.queryLiteLLMTable(model.GatewayID)
		if err != nil {
			return "", fmt.Errorf("check gateway_id in litellm table: %w", err)
		}
		if exists {
			// Already registered: return directly, saving a network registration call.
			return model.GatewayID, nil
		}
		// The DB has an id but the gateway lost the row: fall through and register again (overwriting
		// the previous gateway_id).
	}

	// Register the model and return the model_id (UUID) generated by LiteLLM.
	gatewayID, err := g.registerModel(schema, model, provider)
	if err != nil {
		return "", fmt.Errorf("register model: %w", err)
	}
	return gatewayID, nil
}

// Deprovision removes the model from the gateway, keyed by model.GatewayID (the LiteLLM model_id UUID).
// It is idempotent: a row the gateway does not have returns success immediately — otherwise "disable"
// could never clear the local gateway_id when the gateway refuses to delete, and the model would stay
// stuck in the "enabled" state forever.
func (g *ProxyGateway) Deprovision(schema string, model gateway.ModelInput, provider gateway.ProviderInput) error {
	if model.GatewayID == "" {
		return fmt.Errorf("model.GatewayID is empty, cannot deprovision")
	}
	exists, err := g.modelExists(model.GatewayID)
	if err != nil {
		return err
	}
	if !exists {
		return nil
	}
	return g.deleteModel(model.GatewayID)
}

// modelExists reports whether gateway_id is still in the gateway registry.
// It prefers LiteLLM's own registry (a single query), falling back to GET /model/info comparing
// model_info.id when the database is not connected.
func (g *ProxyGateway) modelExists(modelID string) (bool, error) {
	if modelID == "" {
		return false, nil
	}
	g.dbMu.RLock()
	hasDB := g.db != nil
	g.dbMu.RUnlock()
	if hasDB {
		return g.queryLiteLLMTable(modelID)
	}

	items, err := g.listModels()
	if err != nil {
		return false, err
	}
	for _, item := range items {
		if id, _ := item.ModelInfo["id"].(string); id == modelID {
			return true, nil
		}
	}
	return false, nil
}

// DeprovisionAll disables (removes) every model of a schema registered on LiteLLM.
// It prefers LiteLLM's own registry (everything in one query), falling back to GET /model/info when the
// database is not connected. Each row is removed through deleteModel, and the first failure returns an error.
func (g *ProxyGateway) DeprovisionAll(schema string) (int, error) {
	if schema == "" {
		return 0, fmt.Errorf("schema is empty")
	}

	var modelIDs []string

	g.dbMu.RLock()
	db := g.db
	g.dbMu.RUnlock()

	if db != nil {
		// starts_with is used instead of LIKE 'schema:%' — "_" in LIKE is a single-character wildcard,
		// and schema names may contain underscores, so LIKE risks deleting other tenants' models.
		query := fmt.Sprintf("SELECT model_id FROM %s WHERE starts_with(model_name, $1)", liteLLMModelTable)
		rows, err := db.Query(query, schema+":")
		if err != nil {
			return 0, fmt.Errorf("query litellm model table by prefix: %w", err)
		}
		defer rows.Close()

		for rows.Next() {
			var modelID string
			if err := rows.Scan(&modelID); err != nil {
				return 0, fmt.Errorf("scan litellm model row: %w", err)
			}
			modelIDs = append(modelIDs, modelID)
		}
		if err := rows.Err(); err != nil {
			return 0, fmt.Errorf("iterate litellm model rows: %w", err)
		}
	} else {
		// Deletion must still work when the database is unreachable but HTTP is up, otherwise
		// "deprovision everything" would be unusable without a DB connection.
		provisioned, err := g.ListProvisioned(schema)
		if err != nil {
			return 0, err
		}
		for _, p := range provisioned {
			modelIDs = append(modelIDs, p.GatewayID)
		}
	}

	var count int
	for _, id := range modelIDs {
		if err := g.deleteModel(id); err != nil {
			return count, fmt.Errorf("deprovision model %s: %w", id, err)
		}
		count++
	}
	return count, nil
}

// listModels pulls every model record on the gateway through GET /model/info.
func (g *ProxyGateway) listModels() ([]modelInfoItem, error) {
	req, err := http.NewRequest("GET", g.URL+"/model/info", nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("Authorization", "Bearer "+g.MasterKey)

	resp, err := g.client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(resp.Body)
		return nil, fmt.Errorf("model/info returned %d: %s", resp.StatusCode, string(body))
	}

	var result modelInfoResponse
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		return nil, fmt.Errorf("decode model/info response: %w", err)
	}
	return result.Data, nil
}

// ListProvisioned lists the models of a schema registered on the gateway.
// The name on the LiteLLM side is "<schema>:<gateway_model>", so it filters by that prefix; rows without
// a model_info.id can neither be located nor deleted and are skipped.
func (g *ProxyGateway) ListProvisioned(schema string) ([]gateway.ProvisionedModel, error) {
	if schema == "" {
		return nil, fmt.Errorf("schema is empty")
	}
	items, err := g.listModels()
	if err != nil {
		return nil, err
	}

	prefix := schema + ":"
	provisioned := make([]gateway.ProvisionedModel, 0, len(items))
	for _, item := range items {
		if !strings.HasPrefix(item.ModelName, prefix) {
			continue
		}
		id, _ := item.ModelInfo["id"].(string)
		if id == "" {
			continue
		}
		provisioned = append(provisioned, gateway.ProvisionedModel{
			GatewayID:     id,
			ModelName:     item.ModelName,
			LitellmParams: item.LitellmParams,
			ModelInfo:     item.ModelInfo,
		})
	}
	return provisioned, nil
}

// Update overwrites the parameters of a registered model by GatewayID (POST /model/update).
// It reuses the parameter builder of registerModel, so "register" and "align" write the same content.
func (g *ProxyGateway) Update(schema string, model gateway.ModelInput, provider gateway.ProviderInput) error {
	if model.GatewayID == "" {
		return fmt.Errorf("model.GatewayID is empty, cannot update")
	}

	bodyMap := map[string]any{
		"model_id":       model.GatewayID,
		"model_name":     schema + ":" + model.GatewayModel,
		"litellm_params": buildLitellmParamsMap(newLitellmParams(provider, model)),
		"model_info":     buildModelInfoMap(model),
	}

	bodyBytes, err := json.Marshal(bodyMap)
	if err != nil {
		return err
	}

	req, err := http.NewRequest("POST", g.URL+"/model/update", bytes.NewReader(bodyBytes))
	if err != nil {
		return err
	}
	req.Header.Set("Authorization", "Bearer "+g.MasterKey)
	req.Header.Set("Content-Type", "application/json")

	resp, err := g.client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		respBody, _ := io.ReadAll(resp.Body)
		return fmt.Errorf("model/update returned %d: %s", resp.StatusCode, string(respBody))
	}
	return nil
}

// newLitellmParams builds the LiteLLM call parameters:
//   - model uses "<protocol>/<model.Name>" to tell LiteLLM which upstream to call;
//   - api_key / api_base come from the provider;
//   - ExtraConfig is passed through as is (api_version / vertex_project / timeout / max_retries ...).
//
// It is shared by registerModel and Update so the two cannot drift apart.
//
// Mind the precedence: buildLitellmParamsMap writes model / api_key / api_base first and merges
// ExtraConfig afterwards, so a same-named key inside extra_config overrides the form values above.
func newLitellmParams(provider gateway.ProviderInput, model gateway.ModelInput) litellmParams {
	return litellmParams{
		Model:   provider.Protocol + "/" + model.Name,
		APIKey:  provider.APIKey,
		APIBase: provider.URL,
		Extra:   provider.ExtraConfig,
	}
}

// registerModel registers a model through POST /model/new and returns the model_id (UUID) LiteLLM generated.
func (g *ProxyGateway) registerModel(schema string, model gateway.ModelInput, provider gateway.ProviderInput) (string, error) {
	// model_name: the unique identifier inside LiteLLM Proxy, built from the schema plus the model's
	// gateway-side name.
	gatewayModelName := schema + ":" + model.GatewayModel

	params := registerModelParams{
		ModelName:     gatewayModelName,
		LitellmParams: newLitellmParams(provider, model),
	}

	// Custom serialization is used to merge Extra.
	bodyMap := map[string]any{
		"model_name":     params.ModelName,
		"litellm_params": buildLitellmParamsMap(params.LitellmParams),
		"model_info":     buildModelInfoMap(model),
	}

	bodyBytes, err := json.Marshal(bodyMap)
	if err != nil {
		return "", err
	}

	req, err := http.NewRequest("POST", g.URL+"/model/new", bytes.NewReader(bodyBytes))
	if err != nil {
		return "", err
	}
	req.Header.Set("Authorization", "Bearer "+g.MasterKey)
	req.Header.Set("Content-Type", "application/json")

	resp, err := g.client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		respBody, _ := io.ReadAll(resp.Body)
		return "", fmt.Errorf("model/new returned %d: %s", resp.StatusCode, string(respBody))
	}

	// Parse the model_id (UUID) generated by LiteLLM and use it as the gatewayID.
	var result registerModelResponse
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		return "", fmt.Errorf("decode model/new response: %w", err)
	}
	if result.ModelID == "" {
		return "", fmt.Errorf("model/new response missing model_id")
	}
	return result.ModelID, nil
}

// deleteModel removes a model through POST /model/delete, keyed by the LiteLLM model_id (UUID).
func (g *ProxyGateway) deleteModel(modelID string) error {
	bodyMap := map[string]any{
		"id": modelID,
	}
	bodyBytes, err := json.Marshal(bodyMap)
	if err != nil {
		return err
	}

	req, err := http.NewRequest("POST", g.URL+"/model/delete", bytes.NewReader(bodyBytes))
	if err != nil {
		return err
	}
	req.Header.Set("Authorization", "Bearer "+g.MasterKey)
	req.Header.Set("Content-Type", "application/json")

	resp, err := g.client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		respBody, _ := io.ReadAll(resp.Body)
		return fmt.Errorf("model/delete returned %d: %s", resp.StatusCode, string(respBody))
	}
	return nil
}

func buildLitellmParamsMap(p litellmParams) map[string]any {
	m := map[string]any{
		"model":   p.Model,
		"api_key": p.APIKey,
	}
	if p.APIBase != "" {
		m["api_base"] = p.APIBase
	}
	if p.APIVersion != "" {
		m["api_version"] = p.APIVersion
	}
	for k, v := range p.Extra {
		m[k] = v
	}
	return m
}

func buildModelInfoMap(model gateway.ModelInput) map[string]any {
	m := map[string]any{
		"mode": "chat",
	}
	if model.ContextWindow > 0 {
		m["context_window"] = model.ContextWindow
	}
	if model.MaxTokens > 0 {
		m["max_tokens"] = model.MaxTokens
	}
	for k, v := range model.ExtraParams {
		m[k] = v
	}
	return m
}

// Stream performs a streaming call: POST /chat/completions (stream=true).
func (g *ProxyGateway) Stream(ctx context.Context, model gateway.ModelInput, messages []gateway.Message, tools []gateway.ToolDef) (<-chan gateway.StreamChunk, error) {
	reqBody := g.buildChatRequest(model, messages, tools, true)
	bodyBytes, err := json.Marshal(reqBody)
	if err != nil {
		return nil, err
	}

	req, err := http.NewRequestWithContext(ctx, "POST", g.URL+"/chat/completions", bytes.NewReader(bodyBytes))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Authorization", "Bearer "+g.MasterKey)
	req.Header.Set("Content-Type", "application/json")

	resp, err := g.client.Do(req)
	if err != nil {
		return nil, err
	}

	if resp.StatusCode != http.StatusOK {
		respBody, _ := io.ReadAll(resp.Body)
		resp.Body.Close()
		return nil, fmt.Errorf("chat/completions returned %d: %s", resp.StatusCode, string(respBody))
	}

	ch := make(chan gateway.StreamChunk, 64)
	go g.readSSEStream(resp.Body, ch)
	return ch, nil
}

// ---- DeepSeek native tool-call markers (|DSML|), parsed as a fallback ----
//
// Some upstreams (a self-hosted vLLM / SGLang without a tool-call parser enabled) do not restore the
// model's native tool calls into the OpenAI tool_calls field and instead write them into content as
// ordinary text, shaped like:
//
//	<|DSML|function_calls>
//	<|DSML|invoke name="read_skill">
//	<|DSML|parameter name="name" string="true">english-joke-writing</|DSML|parameter>
//	</|DSML|invoke>
//	</|DSML|function_calls>
//
// The transport layer compensates here: it restores the markers into gateway.ToolCall and strips them
// from the text, so that "the tool was never called and the markers leaked to the user" cannot happen.
// The vertical bar accepts both the full-width (｜) and half-width (|) forms, single or doubled, because
// inference frameworks differ in character width.
const (
	dsmlOpen  = `<\s*[|｜]{1,2}\s*DSML\s*[|｜]{1,2}\s*`
	dsmlClose = `</\s*[|｜]{1,2}\s*DSML\s*[|｜]{1,2}\s*`
)

// dsmlHoldback is the number of trailing bytes held back while streaming, so that a half-received marker
// is never pushed to the frontend. It must be >= the longest marker prefix in bytes
// (`<｜｜DSML｜｜` is about 14 bytes).
const dsmlHoldback = 32

var (
	// dsmlStartRe matches a marker start (telling whether the text already entered the marker region,
	// used to delay the push while streaming).
	dsmlStartRe = regexp.MustCompile(dsmlOpen + `(?:function_calls|invoke|parameter)`)
	// dsmlBlockRe matches a whole function_calls block, stripped from the text.
	dsmlBlockRe = regexp.MustCompile(`(?s)` + dsmlOpen + `function_calls\s*>.*?` + dsmlClose + `function_calls\s*>`)
	// dsmlInvokeRe matches a single invoke (tool name plus parameter body).
	dsmlInvokeRe = regexp.MustCompile(`(?s)` + dsmlOpen + `invoke\s+name="([^"]+)"\s*>(.*?)` + dsmlClose + `invoke\s*>`)
	// dsmlParamRe matches a single parameter (name plus attributes plus value).
	dsmlParamRe = regexp.MustCompile(`(?s)` + dsmlOpen + `parameter\s+name="([^"]+)"([^>]*)>(.*?)` + dsmlClose + `parameter\s*>`)
)

// parseDSMLToolCalls parses DeepSeek native tool-call markers out of the text and returns the calls plus
// the text with the markers stripped. Without markers the text is returned untouched (calls is nil), so
// callers can pass it through at zero cost.
func parseDSMLToolCalls(content string) ([]gateway.ToolCall, string) {
	if !strings.Contains(content, "DSML") {
		return nil, content
	}
	invs := dsmlInvokeRe.FindAllStringSubmatch(content, -1)
	if len(invs) == 0 {
		return nil, content
	}
	calls := make([]gateway.ToolCall, 0, len(invs))
	for i, m := range invs {
		tc := gateway.ToolCall{ID: fmt.Sprintf("dsml_%d", i), Name: m[1], Args: map[string]any{}, FromText: true}
		for _, pm := range dsmlParamRe.FindAllStringSubmatch(m[2], -1) {
			key, attrs, val := pm[1], pm[2], strings.TrimSpace(pm[3])
			// With string="true" the value is taken as plain text; otherwise it is decoded as JSON
			// (number / boolean / object).
			if !strings.Contains(attrs, `string="true"`) {
				var v any
				if err := json.Unmarshal([]byte(val), &v); err == nil {
					tc.Args[key] = v
					continue
				}
			}
			tc.Args[key] = val
		}
		calls = append(calls, tc)
	}
	// Strip the markers: remove the whole function_calls block first, then any bare invoke it did not wrap.
	cleaned := dsmlBlockRe.ReplaceAllString(content, "")
	cleaned = dsmlInvokeRe.ReplaceAllString(cleaned, "")
	return calls, strings.TrimSpace(cleaned)
}

// safeEmitLen returns how many bytes of pending can be pushed safely: a multi-byte character is never
// cut in half. want is the desired byte count; the result is rounded down to the nearest rune start.
// Slicing by byte count while streaming would split characters, and the downstream json.Marshal would
// render the invalid bytes as U+FFFD.
func safeEmitLen(pending string, want int) int {
	if want <= 0 {
		return 0
	}
	if want > len(pending) {
		want = len(pending)
	}
	// The end of the string (want == len(pending)) is always a boundary; otherwise fall back to the
	// nearest rune start.
	for want > 0 && want < len(pending) && !utf8.RuneStart(pending[want]) {
		want--
	}
	return want
}

// readSSEStream reads the SSE stream and writes it into the channel.
func (g *ProxyGateway) readSSEStream(body io.ReadCloser, ch chan<- gateway.StreamChunk) {
	defer body.Close()
	defer close(ch)

	scanner := bufio.NewScanner(body)
	// A larger buffer keeps long lines from being truncated.
	scanner.Buffer(make([]byte, 0, 1024*1024), 1024*1024)

	// Accumulate tool calls (tool_calls arrive in fragments while streaming and arguments must be
	// accumulated by index).
	var toolCallAccum map[int]*gateway.ToolCall

	// Accumulate the text and delay the push on |DSML|: when a marker is hit, stop before it and leave the
	// rest to flushTail for parsing / stripping.
	var acc strings.Builder
	emitted := 0
	inDSML := false

	// pushContent accumulates a text increment and pushes as much of the "certainly marker-free" part as
	// possible right away.
	pushContent := func(delta string) {
		if delta == "" {
			return
		}
		acc.WriteString(delta)
		if inDSML {
			return // already inside the marker region, handle it at the end of this turn
		}
		pending := acc.String()[emitted:]
		if loc := dsmlStartRe.FindStringIndex(pending); loc != nil {
			if loc[0] > 0 {
				ch <- gateway.StreamChunk{Content: pending[:loc[0]]}
				emitted += loc[0]
			}
			inDSML = true
			return
		}
		// No complete marker: hold back the trailing dsmlHoldback bytes (they may contain half a marker)
		// and push the rest immediately.
		// Note that this rounds down to a rune boundary, so a multi-byte character is never cut in half
		// (which would produce U+FFFD garbage).
		if n := safeEmitLen(pending, len(pending)-dsmlHoldback); n > 0 {
			ch <- gateway.StreamChunk{Content: pending[:n]}
			emitted += n
		}
	}

	// flushTail runs at the end of a turn: it parses the |DSML| markers, pushes the remaining clean text
	// and returns the parsed tool calls.
	flushTail := func() []gateway.ToolCall {
		calls, clean := parseDSMLToolCalls(acc.String())
		if n := safeEmitLen(clean, len(clean)); n > emitted {
			ch <- gateway.StreamChunk{Content: clean[emitted:n]}
			emitted = n
		}
		return calls
	}

	for scanner.Scan() {
		line := scanner.Text()
		if line == "" {
			continue
		}
		if !strings.HasPrefix(line, "data: ") {
			continue
		}
		data := strings.TrimPrefix(line, "data: ")
		if data == "[DONE]" {
			if calls := flushTail(); len(calls) > 0 {
				ch <- gateway.StreamChunk{ToolCalls: calls}
			}
			ch <- gateway.StreamChunk{Done: true}
			return
		}

		var chunk streamChunk
		if err := json.Unmarshal([]byte(data), &chunk); err != nil {
			ch <- gateway.StreamChunk{Error: fmt.Errorf("unmarshal stream chunk: %w", err)}
			return
		}

		for _, choice := range chunk.Choices {
			// Handle the content (including the delayed push of |DSML| markers).
			pushContent(choice.Delta.Content)
			// Handle the reasoning content.
			if choice.Delta.ReasoningContent != "" {
				ch <- gateway.StreamChunk{ReasoningContent: choice.Delta.ReasoningContent}
			}
			// Handle tool calls (accumulating the fragments).
			if len(choice.Delta.ToolCalls) > 0 {
				if toolCallAccum == nil {
					toolCallAccum = make(map[int]*gateway.ToolCall)
				}
				for _, tc := range choice.Delta.ToolCalls {
					idx := tc.Index
					if toolCallAccum[idx] == nil {
						toolCallAccum[idx] = &gateway.ToolCall{
							ID:   tc.ID,
							Name: tc.Function.Name,
						}
					} else {
						if tc.ID != "" {
							toolCallAccum[idx].ID = tc.ID
						}
						if tc.Function.Name != "" {
							toolCallAccum[idx].Name = tc.Function.Name
						}
					}
					// Accumulate arguments (fragments of a JSON string).
					if tc.Function.Arguments != "" {
						if toolCallAccum[idx].Args == nil {
							toolCallAccum[idx].Args = map[string]any{"_raw_arguments": tc.Function.Arguments}
						} else {
							if raw, ok := toolCallAccum[idx].Args["_raw_arguments"].(string); ok {
								toolCallAccum[idx].Args["_raw_arguments"] = raw + tc.Function.Arguments
							}
						}
					}
				}
			}
			// finish_reason means this choice is done.
			if choice.FinishReason != nil && *choice.FinishReason != "" {
				var calls []gateway.ToolCall
				// Standard OpenAI tool_calls (when present): parse the accumulated arguments JSON.
				if toolCallAccum != nil {
					for i := 0; i < len(toolCallAccum); i++ {
						tc := toolCallAccum[i]
						if tc == nil {
							continue
						}
						if raw, ok := tc.Args["_raw_arguments"].(string); ok {
							var args map[string]any
							if err := json.Unmarshal([]byte(raw), &args); err == nil {
								tc.Args = args
							} else {
								tc.Args = map[string]any{"_raw": raw}
							}
						}
						calls = append(calls, *tc)
					}
					toolCallAccum = nil
				}
				// Merge the |DSML| tool calls that came out as plain text in the body.
				calls = append(calls, flushTail()...)
				if len(calls) > 0 {
					ch <- gateway.StreamChunk{ToolCalls: calls}
				}
				ch <- gateway.StreamChunk{Done: true}
				return
			}
		}
	}

	if err := scanner.Err(); err != nil {
		ch <- gateway.StreamChunk{Error: err}
		return
	}
	// The stream ended normally without a [DONE].
	if calls := flushTail(); len(calls) > 0 {
		ch <- gateway.StreamChunk{ToolCalls: calls}
	}
	ch <- gateway.StreamChunk{Done: true}
}

// Generate performs a non-streaming call: POST /chat/completions (stream=false).
func (g *ProxyGateway) Generate(ctx context.Context, model gateway.ModelInput, messages []gateway.Message, tools []gateway.ToolDef) (gateway.GenerateResponse, error) {
	reqBody := g.buildChatRequest(model, messages, tools, false)
	bodyBytes, err := json.Marshal(reqBody)
	if err != nil {
		return gateway.GenerateResponse{}, err
	}

	req, err := http.NewRequestWithContext(ctx, "POST", g.URL+"/chat/completions", bytes.NewReader(bodyBytes))
	if err != nil {
		return gateway.GenerateResponse{}, err
	}
	req.Header.Set("Authorization", "Bearer "+g.MasterKey)
	req.Header.Set("Content-Type", "application/json")

	resp, err := g.client.Do(req)
	if err != nil {
		return gateway.GenerateResponse{}, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		respBody, _ := io.ReadAll(resp.Body)
		return gateway.GenerateResponse{}, fmt.Errorf("chat/completions returned %d: %s", resp.StatusCode, string(respBody))
	}

	var result chatResponse
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		return gateway.GenerateResponse{}, fmt.Errorf("decode chat response: %w", err)
	}

	var response gateway.GenerateResponse
	if len(result.Choices) > 0 {
		choice := result.Choices[0]
		// content may be a string or null.
		if len(choice.Message.Content) > 0 && string(choice.Message.Content) != "null" {
			var contentStr string
			if err := json.Unmarshal(choice.Message.Content, &contentStr); err == nil {
				response.Content = contentStr
			} else {
				response.Content = string(choice.Message.Content)
			}
		}
		// Thinking content: aligned with the streaming branch, non-streaming mode must not drop reasoning.
		response.ReasoningContent = choice.Message.ReasoningContent
		// Parse tool calls.
		for _, tc := range choice.Message.ToolCalls {
			var args map[string]any
			if tc.Function.Arguments != "" {
				if err := json.Unmarshal([]byte(tc.Function.Arguments), &args); err != nil {
					args = map[string]any{"_raw": tc.Function.Arguments}
				}
			}
			response.ToolCalls = append(response.ToolCalls, gateway.ToolCall{
				ID:   tc.ID,
				Name: tc.Function.Name,
				Args: args,
			})
		}
		// If |DSML| native tool-call markers leaked into the body (the upstream did not parse them),
		// restore them and strip them.
		if dsmlCalls, cleaned := parseDSMLToolCalls(response.Content); len(dsmlCalls) > 0 {
			response.Content = cleaned
			response.ToolCalls = append(response.ToolCalls, dsmlCalls...)
		}
	}

	return response, nil
}

// buildChatRequest builds the chat/completions request body (carried as a map, with extra_params passed
// through at the top level).
func (g *ProxyGateway) buildChatRequest(model gateway.ModelInput, messages []gateway.Message, tools []gateway.ToolDef, stream bool) map[string]any {
	req := map[string]any{
		"model":    model.GatewayModel,
		"messages": messages,
		"stream":   stream,
	}

	// Optional parameters.
	if model.Temperature > 0 {
		req["temperature"] = model.Temperature
	}
	if model.TopP > 0 {
		req["top_p"] = model.TopP
	}
	if model.MaxTokens > 0 {
		req["max_tokens"] = model.MaxTokens
	}

	// Build the tool definitions.
	if len(tools) > 0 {
		toolsList := make([]map[string]any, 0, len(tools))
		for _, t := range tools {
			toolsList = append(toolsList, map[string]any{
				"type": "function",
				"function": map[string]any{
					"name":        t.Name,
					"description": t.Description,
					"parameters":  t.Parameters,
				},
			})
		}
		req["tools"] = toolsList
	}

	// extra_params all go into extra_body: LiteLLM does not validate them, expands them and passes them
	// through to the upstream instead of raising UnsupportedParamsError.
	if len(model.ExtraParams) > 0 {
		eb, _ := req["extra_body"].(map[string]any)
		if eb == nil {
			eb = make(map[string]any)
		}
		for k, v := range model.ExtraParams {
			if _, exists := eb[k]; !exists {
				eb[k] = v
			}
		}
		req["extra_body"] = eb
	}

	return req
}
