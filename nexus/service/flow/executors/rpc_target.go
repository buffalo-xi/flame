// rpcEndpointProgress is one progress item emitted while an endpoint of this tenant runs.
// Category comes from the Category* constants in agent/core; Meta is only set for tool-like events.
type rpcEndpointProgress struct {
	Message  string
	Category string
	Meta     map[string]interface{}
}

// findRpcEndpoint locates an rpc endpoint of this tenant by **endpoint name**.
//
// Why not an id: an endpoint name always equals the entity name, uniqueness is guaranteed at creation, and
// syncEndpoints keeps the endpoint name in step on a rename; an id, on the other hand, is regenerated by
// "export -> import into another tenant", which would leave the id inside a diagram dangling.
func findRpcEndpoint(authInfo *auth.AuthInfo, name string) (*models.SvcEndpoint, error) {
	name = strings.TrimSpace(name)
	if name == "" {
		return nil, nil
	}
	// exposed is not filtered: a direct call inside this tenant may use an endpoint that is not exposed
	return svcendpoints.NewRepository().FindByName(authInfo, "rpc", name)
}

// runEndpoint runs an RPC endpoint of this tenant in process (target_type=agent/flow) and does not check
// exposed (a direct call inside this tenant may use an endpoint available only to the tenant).
//
// callDepth is the caller's depth (0 at the top level): an agent passes tools.Context.CallDepth, an rpc node
// passes ExecContext.CallDepth. Execution is handed down with callDepth+1.
//
// wantProgress comes from the node config (rpcCfg.progress, off by default): when false the run is synchronous
// and only the final result is taken, without consuming the progress channel — there is no wire in process,
// but "do I want this progress" should still be expressed explicitly by the caller, otherwise every node call
// collects the agent's thinking / text for nothing.
// Returns (result, isError, err): err != nil means the node failed; isError=true means a business error.
//
// scope is the draft scope of a debug session: when non-nil and "follow the dependencies' drafts" is on, the
// called flow reads drafts and records them in the scope; when nil (a real entry point) it reads the released
// version. It is an in-memory property of this execution and enters no cross-process protocol — which is why
// an external call naturally has no scope.
func runEndpoint(
	ctx context.Context,
	authInfo *auth.AuthInfo,
	sessionID string,
	callDepth int,
	callChain []string,
	endpointName string,
	arguments map[string]interface{},
	wantProgress bool,
	scope *flow.DebugScope,
	onProgress func(p rpcEndpointProgress),
) (string, bool, error) {
	// An endpoint is always located by name: the name is unique inside the tenant and follows a rename, while
	// an id is regenerated by export and import
	ep, err := findRpcEndpoint(authInfo, endpointName)
	if err != nil {
		return "", false, fmt.Errorf("failed to look up the RPC endpoint: %w", err)
	}
	if ep == nil {
		return "", false, fmt.Errorf("RPC endpoint not found: %s", endpointName)
	}

	// Call-depth guard: agent -> local flow endpoint -> rpc node -> agent endpoint -> ... forms a cycle, and
	// every cross-run hop creates a fresh ExecContext (each counting from zero), so convergence can only come
	// from depth.
	//
	// The limit is the flow-side recursion depth (flow_configs.max_recursion_depth, 10 by default): the main
	// shape of this chain is flow orchestration, and applying the agent's 3 layers would wrongly clip an
	// A->B->C->D pipeline. A chain involving agents has its own stricter gate (see agent/localendpoint.go), each
	// governing its own semantics.
	//
	// A configured -1 / 0 ("unlimited") is **not honoured** here; it falls back to the default — pure flow
	// calls have no other constraint (the agent gate is not on this chain), so one misconfiguration switching
	// this gate off would leave it wide open.
	next := callDepth + 1
	if maxDepth := resolveEndpointDepthLimit(authInfo.Schema); next > maxDepth {
		return "", false, fmt.Errorf(
			"call depth exceeded (level %d, limit %d): refusing to call endpoint %q - check whether an agent and a flow call each other",
			next, maxDepth, ep.Name)
	}

	// Cycle detection: reject immediately when the target entity is already in the ancestor chain (f -> a -> f)
	// instead of waiting for the depth to run out. It comes after the depth check, because an exceeded level is
	// easier to understand and should be reported first.
	// Sibling fan-out is unaffected: several rpc nodes in one flow read the same chain, and it holds only
	// ancestors.
	self := callchain.Key(ep.TargetType, ep.TargetID)
	if callchain.Contains(callChain, self) {
		return "", false, fmt.Errorf("circular call detected: %s is already in this call chain (%s)", self, callchain.Format(callChain))
	}
	nextChain := callchain.Append(callChain, self)

	switch ep.TargetType {
	case "agent":
		// A debug session follows the agent draft and records it; a real run reads the released version (and is
		// refused when there is none)
		return runAgentEndpoint(ctx, authInfo, sessionID, next, nextChain, ep.TargetID, arguments, wantProgress, scope, onProgress)
	case "flow":
		return runFlowEndpoint(ctx, authInfo, sessionID, next, nextChain, ep.TargetID, arguments, wantProgress, scope, onProgress)
	default:
		return "", false, fmt.Errorf("unsupported target_type %q", ep.TargetType)
	}
}

// resolveEndpointDepthLimit is the depth limit of the endpoint call chain (always positive).
//
// The narrowing lives in flowconfig.DepthLimit so the intra-flow call node and this cross-flow gate always read the
// same number: both are tenant-level, and neither accepts "unlimited".
func resolveEndpointDepthLimit(schema string) int {
	return flowconfig.Resolve(schema).DepthLimit()
}

// runFlowEndpoint runs a flow-type endpoint.
//
// sessionID is passed through the same way as runAgentEndpoint: the sub-flow and its parent land in the same
// users/{uid}/sessions/{sid}/ area. It used to be missing here — agent->flow and flow->agent shared the session
// while flow->flow did not, so a sub-flow's artefacts all landed in runs/ and were deleted when the call ended,
// leaving nothing to find afterwards.
//
// With wantProgress the run calls back with progress as it goes; without it the run is synchronous and only the
// final result is returned. On a cross-process MCP / RPC endpoint "do I want progress" is expressed by
// params._meta.progressToken; this is an in-process direct call, so the equivalent lives in the node config
// (rpcCfg.progress).
func runFlowEndpoint(ctx context.Context, authInfo *auth.AuthInfo, sessionID string, callDepth int, callChain []string, flowId string, input map[string]interface{}, wantProgress bool, scope *flow.DebugScope, onProgress func(p rpcEndpointProgress)) (string, bool, error) {
	repo := flows.NewRepository()

	// Read the entity row first: the status and name come from there; the definition column is then chosen as
	// "draft or released version".
	Instance, err := repo.GetFlow(authInfo, flowId)
	if err != nil {
		return "", false, fmt.Errorf("failed to get the flow instance: %w", err)
	}
	// A deprecated flow cannot run: an internal call (an rpc node calling directly inside this tenant) goes
	// through exactly here, and runEndpoint explicitly **does not check exposed**, so this is the only
	// unconditional interception point.
	if !models.IsRunnable(int(Instance.Status)) {
		return "", false, fmt.Errorf("flow %q is deprecated and cannot be called", Instance.Name)
	}

	// The single fork between "debug runs the draft, production runs the released version":
	//   - with a scope (this execution comes from the editor debugger / a run_flow trial): read the working copy
	//     and record it;
	//   - without one (MCP / RPC / the agent's local__ and other real entry points): the released version is
	//     mandatory, and having none is refused — never quietly fall back to the draft, or the word "released"
	//     means nothing.
	if scope.Enabled() {
		scope.RecordDraft("flow", flowId, Instance.Name, "the debug session follows the draft")
	} else {
		released, perr := repo.GetCurrentFlowVersion(authInfo, flowId)
		if errors.Is(perr, flows.ErrNoReleasedVersion) {
			return "", false, fmt.Errorf(
				"flow %q has no released version yet: a production call only runs released versions, so release it from the editor and retry", Instance.Name)
		}
		if perr != nil {
			return "", false, fmt.Errorf("failed to get the released version of flow %q: %w", Instance.Name, perr)
		}
		Instance = released
	}

	// The depth is handed down with the flow: copy the input, then inject _call_depth (NewFlow strips it, so
	// business arguments are not polluted).
	// It must be copied rather than changed in place: input is the map the caller (the rpc node / tool
	// arguments) still holds.
	flowInput := input
	if flowInput == nil {
		flowInput = make(map[string]interface{}, 1)
	} else {
		cp := make(map[string]interface{}, len(flowInput)+1)
		for k, v := range flowInput {
			cp[k] = v
		}
		flowInput = cp
	}
	flowInput["_call_depth"] = callDepth
	// The chain is handed down with the flow: NewFlow's extractCallChain strips it, so business arguments are
	// not polluted
	if len(callChain) > 0 {
		flowInput[callchain.ArgumentKey] = callChain
	}
	// The session is handed down with the flow: NewFlow's extractSessionID strips it, so business arguments are
	// not polluted
	if sessionID != "" {
		flowInput["session_id"] = sessionID
	}

	execCtx, err := NewFlow(Instance, flowInput, conv.ToString(nil), uuid.Must(uuid.NewV7()).String(), authInfo.Schema, authInfo.ID, ctx)
	if err != nil {
		return "", false, fmt.Errorf("failed to initialise the flow run: %w", err)
	}
	// The scope travels further down: an rpc node inside the sub-flow decides which copy its own sub-calls read
	// from the same scope
	execCtx.DebugScope = scope

	if !wantProgress {
		// Synchronous: the progress/result channels are not consumed (an inner write is non-blocking when nobody
		// reads)
		Start(execCtx)
		return endpointFlowResult(execCtx)
	}

	errCh := make(chan error, 1)
	go func() {
		errCh <- Start(execCtx)
		execCtx.CloseChans()
	}()

	progressCh := execCtx.GetProgressChan()
	resultCh := execCtx.GetResultChan()

loop:
	for progressCh != nil || resultCh != nil {
		select {
		case chunk, ok := <-progressCh:
			if !ok {
				progressCh = nil
				continue
			}
			if chunk.Message != "" && onProgress != nil {
				onProgress(rpcEndpointProgress{Message: xjson.SanitizeJSON(core.CleanProgressMarkers(chunk.Message)), Category: chunk.Category})
			}
		case chunk, ok := <-resultCh:
			if !ok {
				resultCh = nil
				continue
			}
			if chunk != "" && onProgress != nil {
				onProgress(rpcEndpointProgress{Message: xjson.SanitizeJSON(chunk), Category: core.CategoryText})
			}
		case <-errCh:
			break loop
		case <-ctx.Done():
			execCtx.CloseChans()
			return "", false, ctx.Err()
		}
	}

	return endpointFlowResult(execCtx)
}

// runAgentEndpoint runs an agent-type endpoint; with wantProgress it calls back with progress as it goes, and
// otherwise only takes the final answer.
func runAgentEndpoint(ctx context.Context, authInfo *auth.AuthInfo, sessionID string, callDepth int, callChain []string, agentID string, input map[string]interface{}, wantProgress bool, scope *flow.DebugScope, onProgress func(p rpcEndpointProgress)) (string, bool, error) {
	agentInst, err := agents.NewRepository().GetAgent(authInfo, agentID)
	if err != nil {
		return "", false, fmt.Errorf("failed to get the agent instance: %w", err)
	}
	// A deprecated agent cannot run (same as runFlowEndpoint: a direct call inside this tenant does not check
	// exposed)
	if !models.IsRunnable(int(agentInst.Status)) {
		return "", false, fmt.Errorf("agent %q is deprecated and cannot be called", agentInst.Name)
	}
	// The super agent can still be started from a flow and is not blocked here: its capabilities should not be
	// discounted because of who calls it (the admin surface edits drafts, so reading the released version would
	// hide what it just created).
	// The cost is that this one cell is outside the scope's control — resolveDefinitionMode makes the supervisor
	// always read drafts, so "production flow -> supervisor" is not reproducible, and troubleshooting should
	// trust the supervisor's draft.
	agentArguments := map[string]interface{}{
		"args":      input,
		"_run_type": "flow",
	}
	// The depth plus user and session are passed through: the called agent's NewAgent reads _call_depth, and
	// when it calls a local tool again the agent side's own limit takes over.
	if callDepth > 0 {
		agentArguments["_call_depth"] = callDepth
	}
	// The chain goes to the agent: when it calls out through rpc__ again it carries the whole chain in
	// _meta.call_chain. It is a top-level reserved key rather than part of args — args are the business
	// arguments the model sees.
	if len(callChain) > 0 {
		agentArguments[callchain.ArgumentKey] = callChain
	}
	// The flow's user and session are passed through: an agent node and a flow share the same area
	if authInfo.ID != "" {
		agentArguments["user_id"] = authInfo.ID
	}
	if sessionID != "" {
		agentArguments["session_id"] = sessionID
	}
	// The output language travels the same way, but only when this run's caller pinned it: the called agent's NewAgent reads
	// the reserved key, and a value that was merely resolved here must not become a demand on the agent's own default. It
	// sits at the top level (next to session_id), so it never becomes a model-visible {{args._output_language}}.
	if core.LanguagePinnedFrom(ctx) {
		agentArguments = core.WithOutputLanguage(agentArguments, core.LanguageHintFrom(ctx))
	}
	// A debug session follows the agent draft and records it (the same rule as following flow drafts); a real run
	// reads the released current version and errors outright when there is none.
	//
	// _follow_drafts is injected explicitly rather than relying on the sub-agent's default: whether drafts spread
	// to the agents / flows it starts should be decided by the scope here, not caught by the implicit convention
	// "the default over there is true" (the day that default changes, behaviour drifts silently).
	if scope.Enabled() {
		scope.RecordDraft("agent", agentID, agentInst.Name, "the debug session follows the draft")
		agent.SetDraftMode(agentArguments)
		agent.SetFollowDrafts(agentArguments, true)
	} else {
		agent.SetReleaseMode(agentArguments)
		agent.SetFollowDrafts(agentArguments, false)
	}
	inst, err := agent.NewAgent(agentInst, authInfo.Schema, agentArguments)
	if err != nil {
		return "", false, fmt.Errorf("failed to initialise the agent: %w", err)
	}
	if inst == nil {
		return "", false, fmt.Errorf("agent %s is unsupported or does not exist", agentID)
	}
	defer inst.Close()

	if !wantProgress {
		// Synchronous: the event channel is not consumed, only the final answer is taken
		if runErr := inst.Stream(context.Background()); runErr != nil {
			return "", false, fmt.Errorf("failed to run the agent: %w", runErr)
		}
		inst.CloseChans()
		return endpointAgentResult(inst)
	}

	errCh := make(chan error, 1)
	go func() {
		errCh <- inst.Stream(context.Background())
		inst.CloseChans()
	}()

	// Consume the structured event channel: thinking and tool calls only appear here.
	eventCh := inst.GetEventChan()

loop:
	for eventCh != nil {
		select {
		case ev, ok := <-eventCh:
			if !ok {
				eventCh = nil
				continue
			}
			if onProgress == nil {
				continue
			}
			if item, has := ev.ToProgress(); has {
				onProgress(rpcEndpointProgress{
					Message:  xjson.SanitizeJSON(item.Message),
					Category: item.Category,
					Meta:     item.Meta,
				})
			}
		case <-errCh:
			break loop
		case <-ctx.Done():
			inst.CloseChans()
			return "", false, ctx.Err()
		}
	}

	return endpointAgentResult(inst)
}

// endpointFlowResult extracts the result from a flow ExecContext: a business error comes back with isError=true.
func endpointFlowResult(execCtx *flow.ExecContext) (string, bool, error) {
	if e := execCtx.GetError(); e != "" {
		return e, true, nil
	}
	return execCtx.GetResult(), false, nil
}

// endpointAgentResult extracts the result from an agent instance: a business error comes back with isError=true.
func endpointAgentResult(inst core.Agent) (string, bool, error) {
	if e := inst.GetError(); e != "" {
		return e, true, nil
	}
	return inst.GetResult(), false, nil
}
