// WorkflowFileName is the entry file of a workflow asset.
//
// A workflow differs from the other three kinds: its body is one JSONB row in {schema}.flows (diagram
// plus variables and limits) and there is no directory on disk. Listing serialises that row into
// FLOW.json and sends it through the same file pipeline (packing / manifest validation / export /
// import / install).
//
// Why not open a separate path for "assets without files": that would mean changing three
// preconditions — PackFilesWith (ErrNoFiles), Package.verify (non-empty manifest) and WritePackage
// (non-empty manifest) — and those three are the pivot of "a package must prove its content is
// complete". Carrying one JSON file through them is a much smaller change.
const WorkflowFileName = "FLOW.json"

// ValidateWorkflowName validates a workflow name: the same character set as agent/skill (letters,
// digits and dashes, ≤64) but for a different reason — a workflow writes no directory, yet its name
// is **used directly as the external tool name**:
//
//	{schema}.flows.name → svc_endpoints.name (Create forces them equal, renames keep them in sync)
//	                    → the tool.name of MCP tools/list
//	                    → the agent-side tool name local__<name> and the grant ref local:rpc:<name>
//
// The latter two have hard character-set constraints (the toolgrant ref regex, the model-side
// function name regex); with a Chinese name the workflow can be created, yet no usable endpoint can
// be listed and no grant can be resolved. It has to be blocked here, and the Chinese intent belongs
// in description (the list and the cards are how people tell flows apart).
func ValidateWorkflowName(name string) error {
	n := strings.TrimSpace(name)
	if n == "" {
		return errors.New("the workflow name is empty")
	}
	if !paths.ValidName(n) {
		return fmt.Errorf("the workflow name %q is not valid: only letters, digits and dashes, no leading dash, at most %d characters. "+
			"It is exposed to the model as the tool name local__<name>, so put the human-readable description in the description field", n, MaxNameLen)
	}
	return nil
}

// WorkflowSnapshot is the structure of FLOW.json: the **content** that can move across tenants.
//
// Deliberately absent:
//
//	id                        regenerated by the target tenant
//	status                    the target tenant creates it in the normal state (1); deprecation is
//	                          only ever set by hand on the local host
//	created_by / updated_by   people and identity do not cross tenants
//	endpoints                 endpoint protocol and listing state are runtime environment
//	                          configuration, not content
//	breakpoints               debug breakpoints are local debug state
//
// Suspected credentials in env_vars and diagram are cleared before packing (see the KindWorkflow
// branch of StripSecrets).
type WorkflowSnapshot struct {
	Name        string          `json:"name"`
	Description string          `json:"description"`
	Diagram     json.RawMessage `json:"diagram,omitempty"`
	Arguments   json.RawMessage `json:"arguments,omitempty"`
	Outputs     json.RawMessage `json:"outputs,omitempty"`
	EnvVars     json.RawMessage `json:"env_vars,omitempty"`
	FlowVars    json.RawMessage `json:"flow_vars,omitempty"`
	// The limits deliberately do not use omitempty: -1 is a meaningful "unlimited" value in the
	// flows table, and omitting the field would be read as 0 by the installer, silently turning
	// "unlimited" into "limited to 0".
	Timeout           int `json:"timeout"`
	MaxRecursionDepth int `json:"max_recursion_depth"`
	MaxNodeCount      int `json:"max_node_count"`
	MaxExecCount      int `json:"max_exec_count"`
	MaxRunRecords     int `json:"max_run_records"`
	MaxSessionRecords int `json:"max_session_records"`
}
