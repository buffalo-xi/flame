// Package callchain maintains the **ancestor chain** of one call across agent / flow / RPC, and detects
// recursive calls with it.
//
// Element format:
//
//	<id>|<kind>     e.g. 3f2a1c40-…-1c0d5b6e9f31|agent
//
// The part before the vertical bar is the entity id and is the **only thing that takes part in duplicate
// detection**; the part after it is the kind (agent / flow), present for log readability only — it may be
// omitted or even wrong, because identity is the id alone: a changed kind, or an endpoint re-pointed at
// another entity, must not be reported as a cycle.
//
// The note section deliberately carries **no tenant schema**: a schema is routing information for this
// instance only, and after a redeployment the same "t0" may point at a completely different tenant, so
// writing it into the chain would only mislead troubleshooting (and duplicate detection only looks at the
// id anyway). Tenant information is already in the request URL, the log fields and the endpoint row; the
// chain need not repeat it.
//
// Semantics (deliberately different from the depth mechanism):
//   - only **ancestors** are recorded: a child call receives "the parent chain plus the parent itself", and
//     sibling branches do not pass it to each other. So "the same child called twice from one parent" (f a
//     a) always passes, while "an entity appearing in its own ancestor chain" (f a f) is always refused;
//   - an inbound / direct internal call appends itself to the tail before passing it on, while an outbound
//     call carries it out **as is** without appending again.
//
// Cost: duplicate detection ignores tenant and kind, relying on "ids are globally unique" (every tenant
// table's primary key is a uuid, so the collision probability is about 2⁻¹²²). In exchange the note section
// can evolve freely without affecting the decision.
//
// Relationship with max_call_depth / max_recursion_depth:
//   - those two are the fallback gates (depth limits) while this package is precise detection (refuse as
//     soon as re-entry is seen); the two complement each other;
//   - the chain is self-reported, so a client may omit or forge it — forging only means "this call is
//     refused", but omitting it means detection cannot happen, so **this package must never replace the
//     depth limits**.
package callchain

import (
	"context"
	"strings"
)

const (
	// MetaKey is the key inside JSON-RPC params._meta (cross-process).
	MetaKey = "call_chain"
	// ArgumentKey is the reserved argument key of a direct in-process call (the same mechanism as
	// _call_depth).
	ArgumentKey = "_call_chain"

	// MaxLen is the hard limit on chain length: a normal stack depth is far below it, so anything longer is
	// treated as a crafted malicious request.
	// Over the limit is refused outright rather than truncated — truncation would help the caller around it.
	MaxLen = 64

	KindAgent = "agent"
	KindFlow  = "flow"

	// noteSep separates "the id that takes part in duplicate detection" from "the note".
	noteSep   = "|"
	formatSep = " → "

	// maxIDLen is the length limit of a single field (id or note).
	maxIDLen = 64
)

// Key builds one entity's element in the chain: <id>|<kind>.
//
// id is the entity's (agent / flow) primary key, not an endpoint id: the execution layer inherently knows who
// it is, while an endpoint id is regenerated by export and import.
// With no kind only the bare id is returned — still usable for duplicate detection, just with less context in
// the log.
func Key(kind, id string) string {
	id = strings.TrimSpace(strings.ToLower(id))
	if id == "" {
		return ""
	}
	if kind == "" {
		return id
	}
	return id + noteSep + strings.ToLower(strings.TrimSpace(kind))
}

// ID takes the part of an element that takes part in duplicate detection (before the vertical bar); with no
// note it is the whole string.
func ID(key string) string {
	if i := strings.Index(key, noteSep); i >= 0 {
		return key[:i]
	}
	return key
}

// Valid reports whether an element is valid. Invalid elements are dropped while parsing — dirty data must not
// reject a normal call.
//
// Validation only looks at "the id is an identifier" plus "the shape of the note section"; the schema / kind
// values inside the note are not enumerated, because when a new kind appears an old version should pass
// rather than drop the whole chain.
func Valid(key string) bool {
	if key == "" {
		return false
	}
	i := strings.Index(key, noteSep)
	if i < 0 {
		return identifier(key) && len(key) <= maxIDLen
	}
	id := key[:i]
	if !identifier(id) || len(id) > maxIDLen {
		return false
	}
	return noteIdent(key[i+1:])
}

// identifier validates an identifier: letters, digits, underscore, dash (a uuid needs dashes).
func identifier(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c == '_' || c == '-' || (c >= '0' && c <= '9') || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') {
			continue
		}
		return false
	}
	return true
}

// noteIdent validates the note section: looser than an id (it additionally allows "/" and "@", leaving room
// for a future "agent@instance" style suffix) but rejecting whitespace and control characters.
// The note takes no part in duplicate detection, so the only goal here is "no strange characters in the log";
// being loose is what lets a peer's new suffix be accepted by an old version instead of dropping the whole
// chain.
func noteIdent(s string) bool {
	if s == "" || len(s) > maxIDLen {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c == '_' || c == '-' || c == '/' || c == '@' ||
			(c >= '0' && c <= '9') || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') {
			continue
		}
		return false
	}
	return true
}

// Contains reports whether a key is already in the chain (the single entry point of the rule: compare the ID
// only, never the note).
func Contains(chain []string, key string) bool {
	want := ID(strings.ToLower(strings.TrimSpace(key)))
	if want == "" {
		return false
	}
	for _, v := range chain {
		if ID(strings.ToLower(v)) == want {
			return true
		}
	}
	return false
}

// Append returns a new slice "chain + key" (the input is not modified, so sibling branches cannot pollute each
// other).
// When the key already exists or is empty the original chain is returned: appending a duplicate changes no
// decision, it only makes the log harder to read.
func Append(chain []string, key string) []string {
	if key == "" || Contains(chain, key) {
		return chain
	}
	out := make([]string, 0, len(chain)+1)
	out = append(out, chain...)
	out = append(out, key)
	return out
}

// Format renders a human-readable chain (for error messages and logs).
func Format(chain []string) string {
	if len(chain) == 0 {
		return "(empty chain)"
	}
	return strings.Join(chain, formatSep)
}

// Normalize turns a chain value from any source into []string, dropping invalid elements and anything past the
// limit.
//
// Accepted types: []string, []any (JSON decoded), a single string.
// Everything is lower-cased: a uuid is lower case in the database while a URL parameter or the frontend may
// send upper case, and without normalising it the same entity would have two spellings and duplicate detection
// would stop working.
// Anything over the limit is truncated to MaxLen: a caller that explicitly sends an over-long chain was
// already rejected in ParseParams, so this is only a defensive fallback.
func Normalize(raw any) []string {
	var src []string
	switch v := raw.(type) {
	case []string:
		src = v
	case []any:
		src = make([]string, 0, len(v))
		for _, item := range v {
			if s, ok := item.(string); ok {
				src = append(src, s)
			}
		}
	case string:
		if v != "" {
			src = []string{v}
		}
	default:
		return nil
	}
	out := make([]string, 0, len(src))
	for _, s := range src {
		s = strings.ToLower(strings.TrimSpace(s))
		if !Valid(s) {
			continue
		}
		out = append(out, s)
		if len(out) >= MaxLen {
			break
		}
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

// RawLen is the raw chain length (used to check the limit before Normalize).
func RawLen(raw any) int {
	switch v := raw.(type) {
	case []string:
		return len(v)
	case []any:
		return len(v)
	}
	return 0
}

// ParseParams takes the chain out of JSON-RPC params (only params._meta.call_chain, the same convention as
// session_id / progressToken).
//
// tooLong means the chain the caller supplied exceeds MaxLen: it must then be **refused outright** rather than
// truncated and continued — the dropped segments may be exactly where the re-entry to detect is hiding.
func ParseParams(params any) (chain []string, tooLong bool) {
	mp, ok := params.(map[string]any)
	if !ok {
		return nil, false
	}
	meta, ok := mp["_meta"].(map[string]any)
	if !ok {
		return nil, false
	}
	raw := meta[MetaKey]
	if RawLen(raw) > MaxLen {
		return nil, true
	}
	return Normalize(raw), false
}

// FromArguments takes the chain out of a direct in-process call's arguments (the _call_chain reserved key).
func FromArguments(args map[string]any) []string {
	if args == nil {
		return nil
	}
	return Normalize(args[ArgumentKey])
}

// WithArguments returns a **new argument map** carrying the chain (the input is not modified).
// With an empty chain the arguments are returned as is, so an ordinary call does not gain an empty key.
func WithArguments(args map[string]any, chain []string) map[string]any {
	if len(chain) == 0 {
		return args
	}
	out := make(map[string]any, len(args)+1)
	for k, v := range args {
		out[k] = v
	}
	out[ArgumentKey] = chain
	return out
}

// ctxKey is a private type, so it cannot collide with another package's context key.
type ctxKey struct{}

// With puts the chain into the context (for an outbound caller to read; the business signature is unchanged).
func With(ctx context.Context, chain []string) context.Context {
	if len(chain) == 0 || ctx == nil {
		return ctx
	}
	return context.WithValue(ctx, ctxKey{}, chain)
}

// From takes the chain out of the context; nil when there is none.
func From(ctx context.Context) []string {
	if ctx == nil {
		return nil
	}
	chain, _ := ctx.Value(ctxKey{}).([]string)
	return chain
}
