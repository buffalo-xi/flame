#Requires -Version 5.1
<#
.SYNOPSIS
    Cross-compile the PoC binaries and the desktop bundle into deploy/poc/out, so they can be mounted into the container
    instead of rebuilding the image.

.DESCRIPTION
    The image already contains a working build (it compiles in a builder stage), so this script is only for the
    "change the code, keep the same image" loop:

        powershell -File deploy/poc/build.ps1
        docker restart flame

    Products (all gitignored):
        out/bin/{nexus,seedpoc,sandboxd,codehost,browserd,browserhost}   linux/amd64, no extension, statically linked
        out/dist/                                                the built desktop bundle
        out/compose-mounts.yml                                   a compose override that mounts the two above into the
                                                                 flame container (so `up -d` does not rebuild)

    The binaries are Linux binaries: they will not run on Windows. That is the point — they are built for the container.
    The LLM gateway is a separate container running the official LiteLLM image; it is unaffected by this script.

.PARAMETER OutDir
    Where to write the products. Defaults to <this script>\out.

.PARAMETER SkipDesktop
    Only build the Go binaries (the frontend build needs node_modules and takes a while).

.PARAMETER Docker
    Also (re)build the image and restart the container afterwards. Off by default: this script never talks to Docker
    unless asked.

.EXAMPLE
    powershell -File deploy/poc/build.ps1
    powershell -File deploy/poc/build.ps1 -SkipDesktop
    powershell -File deploy/poc/build.ps1 -Docker
#>
param(
    [string]$OutDir = (Join-Path $PSScriptRoot 'out'),
    [switch]$SkipDesktop,
    [switch]$Docker
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$binDir = Join-Path $OutDir 'bin'
$distDir = Join-Path $OutDir 'dist'
New-Item -ItemType Directory -Force -Path $binDir | Out-Null

$oldCgo = $env:CGO_ENABLED
$oldGoos = $env:GOOS
$oldGoarch = $env:GOARCH
try {
    # Pure Go everywhere (pgx / chromedp / x-crypto), so a static cross-compile needs no C toolchain.
    $env:CGO_ENABLED = '0'
    $env:GOOS = 'linux'
    $env:GOARCH = 'amd64'

    function Build-Go {
        param([string]$ModuleDir, [string]$Package, [string]$Name)

        $out = Join-Path $binDir $Name
        Push-Location (Join-Path $repoRoot $ModuleDir)
        try {
            & go build -trimpath -ldflags '-s -w' -o $out $Package
            if ($LASTEXITCODE -ne 0) { throw "go build failed: $ModuleDir $Package" }
        }
        finally {
            Pop-Location
        }
        $item = Get-Item -LiteralPath $out
        Write-Host ('  {0,-13} {1,7:N1} MB' -f $Name, ($item.Length / 1MB)) -ForegroundColor Green
    }

    Write-Host "cross-compiling (linux/amd64) -> $binDir" -ForegroundColor Cyan
    Build-Go 'nexus' './cmd' 'nexus'
    Build-Go 'nexus' './cmd/seedpoc' 'seedpoc'
    Build-Go 'sandboxd' '.' 'sandboxd'
    Build-Go 'sandboxd' './cmd/codehost' 'codehost'
    Build-Go 'browserd' './cmd/browserd' 'browserd'
    Build-Go 'browserd' './cmd/browserhost' 'browserhost'

    if (-not $SkipDesktop) {
        Write-Host "building the desktop bundle" -ForegroundColor Cyan
        & npm --prefix (Join-Path $repoRoot 'desktop') run build
        if ($LASTEXITCODE -ne 0) { throw 'npm run build failed' }

        if (Test-Path -LiteralPath $distDir) { Remove-Item -LiteralPath $distDir -Recurse -Force }
        Copy-Item -LiteralPath (Join-Path $repoRoot 'desktop\dist') -Destination $distDir -Recurse
        Write-Host "  dist/ copied to $distDir" -ForegroundColor Green
    }
}
finally {
    $env:CGO_ENABLED = $oldCgo
    $env:GOOS = $oldGoos
    $env:GOARCH = $oldGoarch
}

# A compose override that mounts the products just built into the flame container. Generated under out/ (gitignored)
# rather than kept in docker-compose.yml, so the default file stays "run what the image contains".
$composeFile = Join-Path $PSScriptRoot 'docker-compose.yml'
$overridePath = Join-Path $OutDir 'compose-mounts.yml'
$overrideLines = @(
    '# Generated by build.ps1 - mounts the locally built products into the flame container.'
    'services:'
    '  flame:'
    '    volumes:'
    ('      - "' + ($binDir -replace '\\', '/') + ':/opt/flame/bin-mount:ro"')
)
if (-not $SkipDesktop) {
    $overrideLines += ('      - "' + ($distDir -replace '\\', '/') + ':/usr/share/nginx/html-mount:ro"')
}
$overrideLines | Set-Content -Encoding ASCII -Path $overridePath

Write-Host ''
Write-Host 'run with the freshly built products (no image rebuild):' -ForegroundColor Cyan
Write-Host "  docker compose -f `"$composeFile`" -f `"$overridePath`" up -d"
Write-Host ''
Write-Host 'already running? apply the new binaries with:  docker restart flame' -ForegroundColor Yellow

if ($Docker) {
    Write-Host ''
    Write-Host 'building the flame image (this takes minutes on the first run)' -ForegroundColor Cyan
    & docker compose -f $composeFile build flame
    if ($LASTEXITCODE -ne 0) { throw 'docker compose build failed' }

    & docker compose -f $composeFile up -d
    if ($LASTEXITCODE -ne 0) { throw 'docker compose up failed' }
    Write-Host 'stack started; open http://localhost:27001' -ForegroundColor Green
}
